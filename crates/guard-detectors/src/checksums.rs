//! Каскад 0 — детекторы контрольных сумм документов РФ и ЕС (SPEC §2 «Каскад 0»,
//! SPEC §10 п.3; первичка формул и эталонов —
//! [`docs/dep-verify-algorithms.md`](../../../docs/dep-verify-algorithms.md)).
//!
//! SPEC — вторичник; его опровергнутые утверждения здесь **не** реализуются:
//! ОГРНИП = mod 11 (вердикт §4: mod 13), «Мир» 2200–2204 (вердикт §5a: весь
//! 22xxxx), «в РФ IBAN нет» (вердикт §6a: RU существует, 33), корсчета по
//! «385-П/2020» (вердикт §7a: 383-П + 579-П), приказ «ММ-3-6/2010@» (§1–2:
//! реальный ММВ-7-6/534@).
//!
//! Единственный класс, где сверка с первичкой породила **лишнее** отсевание, а
//! не только подтверждение: структура ОГРН/ОГРНИП. Первичка — п.7 Приказа
//! Минфина России от 30.10.2017 № 165н (§4), см. [`ogrn_structure_ok`]; SPEC о
//! разрядах молчит, поэтому это не опровержение транскрипта, а закрытие хвоста
//! «номер акта ОГРН не найден».
//!
//! Соглашения модуля:
//! - Детектор принимает срез, который нашёл regex-слой каскада 0 поверх
//!   [`normalize`][super::normalize] (для форматированных номеров — уже
//!   нормализованные голые цифры), и возвращает `Option<bool>`:
//!   `Some(true)` — номер валиден; `Some(false)` — формат нашего класса,
//!   чексумма/структура не сходится; `None` — строка не относится к классу
//!   (чужая длина, не-цифры, неизвестная страна) — решение о классе принимает
//!   вызывающий слой.
//! - Приоритет детерминированного валидатора 1.0 и нейросетью не понижается
//!   (AGENTS §Инженерные инварианты); `mir_bin` — только подсказка типа,
//!   никогда фильтр выбрасывания (§5a).
//! - Эталонные векторы в тестах перенесены таблицами из документа; ожидаемое не
//!   вычисляется проверяемой функцией (AGENTS §Дисциплина фактов п.3).
//! - Значения номеров не попадают в `Display`/логи — печатаем причину без тела.

/// Классификация отказа разбора числа.
///
/// `Display` намеренно не печатает содержимое: тело номера — персональные
/// данные, в логи они не попадают (AGENTS §Инженерные инварианты, Debug-only
/// `[REDACTED]`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ParseNum {
    /// Внутри тела встретилась не-ASCII цифра.
    NotDigit,
    /// Тело не влезает в `u128` (для ОГРН/ОГРНИП невозможно: ≤15 цифр).
    Overflow,
}

impl core::fmt::Display for ParseNum {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::NotDigit => f.write_str("не-цифра в теле номера"),
            Self::Overflow => f.write_str("тело номера не влезает в u128"),
        }
    }
}

impl std::error::Error for ParseNum {}

/// Порождающая последовательность весов ИНН (§1: «удвоение по модулю 11,
/// младшая цифра, сдвиг назад»). Все три случая — окна одного массива:
/// ИНН-10 = `W10`, ИНН-12 `cd11` = `A11`, ИНН-12 `cd12` = `B12` (§1–§2).
const W10: [u32; 9] = [2, 4, 10, 3, 5, 9, 4, 6, 8];
/// §2: веса `cd11` по цифрам 1..10 = `[7, 2, 4, 10, 3, 5, 9, 4, 6, 8]`.
const A11: [u32; 10] = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8];
/// §2: веса `cd12` по цифрам 1..11 = `A11` с дописанной `3` в начало.
const B12: [u32; 11] = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8];

/// Сумма произведений цифр на веса → `mod 11` → **младшая цифра остатка**
/// (формулировка §1/§2; «×4 %10» из SPEC — артефакт пересказа, §4).
fn weighted_mod11(digits: &[u8], weights: &[u32]) -> Option<u8> {
    if digits.len() != weights.len() {
        return None;
    }
    let sum: u32 = core::iter::zip(digits, weights)
        .map(|(&d, &w)| u32::from(d) * w)
        .sum();
    Some(((sum % 11) % 10) as u8)
}

/// Строка ASCII-цифр → значения цифр `0..9`; `None` при не-цифре.
///
/// Выделение на типичном входе ≤33 байта (IBAN RU) — в рамках каскада-0
/// (<1 мс, SPEC §2); аллокацию снимет ленивая версия, когда придёт горячий путь.
fn ascii_digits(input: &[u8]) -> Option<Vec<u8>> {
    let mut out = Vec::with_capacity(input.len());
    for &b in input {
        if b.is_ascii_digit() {
            out.push(b - b'0');
        } else {
            return None;
        }
    }
    Some(out)
}

/// 16-ричного смысла здесь нет: ASCII-цифры → `u128` (§4: «первые N цифр как
/// целое → mod»). `u128` заведомо хватает: максимум 14 цифр < 10^14.
fn digits_to_u128(digits: &[u8]) -> Result<u128, ParseNum> {
    let mut n: u128 = 0;
    for &d in digits {
        if d > 9 {
            return Err(ParseNum::NotDigit);
        }
        n = n * 10 + u128::from(d);
    }
    Ok(n)
}

/// Младшая цифра остатка `body mod m` (§4: «mod → LAST digit»).
fn last_digit_of_mod(body: u128, m: u32) -> u8 {
    ((body % u128::from(m)) % 10) as u8
}

/// Проверка ИНН юридического лица (10 цифр).
///
/// Формула — [§1](../../../docs/dep-verify-algorithms.md): `Σ INN[i]·W10[i] →
/// mod 11 → младшая цифра` = цифра 10. Взят вариант «9 весов» (§1: математически
/// эквивалентен 10-весовому, но не читает контрольную цифру при вычислении).
///
/// Первичка: номера ИНН — НК РФ ст. 83–85; **алгоритм контрольного числа не
/// опубликован ни в одном акте ФНС в виде формулы** — живёт в форматах обмена
/// ЕПМВ; акт-первоисточник форматов: приказ ФНС России **от 09.11.2010
/// № ММВ-7-6/534@** (утратил силу с 01.01.2017 — приказ ММВ-7-6/712@, §1).
/// Номер «ММ-3-6/2010@, прил. 4» из SPEC опровергнут (§1 «Коррекция ссылки»);
/// веса «57 36 21 17» — выдумка транскрипта.
///
/// `None` — не 10 ASCII-цифр.
pub fn inn10(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 10 {
        return None;
    }
    Some(weighted_mod11(&d[..9], &W10)? == d[9])
}

/// Проверка ИНН физического лица / ИП (12 цифр), двухступенчатая.
///
/// Формула — [§2](../../../docs/dep-verify-algorithms.md):
/// `cd11 = (Σ₁..₁₀·A) mod 11 mod 10`, `cd12 = (Σ₁..₁₁·B) mod 11 mod 10`;
/// валиден ⟺ `INN[11]==cd11 && INN[12]==cd12`. Первичка та же, что у
/// [`inn10`]. `None` — не 12 ASCII-цифр.
pub fn inn12(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 12 {
        return None;
    }
    Some(weighted_mod11(&d[..10], &A11)? == d[10] && weighted_mod11(&d[..11], &B12)? == d[11])
}

/// Контрольное число СНИЛС по 9 цифрам тела: веса `9..1`, mod 101 с правилом
/// §3: `S < 100 → S`; `S ∈ {100, 101} → 00`; `S > 101 → S mod 101`, и остатки
/// 100/101 снова дают `00`.
fn snils_control(d9: &[u8]) -> Option<u8> {
    if d9.len() != 9 || !d9.iter().all(|&x| x < 10) {
        return None;
    }
    let sum: u32 = core::iter::zip(d9, 0u32..)
        .map(|(&digit, i)| u32::from(digit) * (9 - i))
        .sum();
    // §3: S < 100 → S; S ∈ {100, 101} → 00; S > 101 → S mod 101, остатки
    // 100/101 снова дают 00.
    Some(if sum < 100 {
        u8::try_from(sum).unwrap_or(0)
    } else if sum == 100 || sum == 101 {
        0
    } else {
        match sum % 101 {
            r if r < 100 => u8::try_from(r).unwrap_or(0),
            _ => 0,
        }
    })
}

/// Проверка СНИЛС по 11 голым ASCII-цифрам (`XXX-XXX-XXX CC` после
/// нормализации; §3: «Формат ввода жёсткий … нормализуйте 11 голых цифр»).
///
/// Формула и правила — [§3](../../../docs/dep-verify-algorithms.md).
/// Первоисточник: «Правила расчета контрольной суммы СНИЛС», ТФОМС Ростовской
/// области (страница получена при верификации; в шапке — отсылка к приказу
/// ФОМС от 04.06.2018 № 104); выше по иерархии — Приказ Минздравсоцразвития
/// России от 15.12.2009 № 987н (полный текст в свободном доступе не получен).
///
/// Дополнительные правила §3 (в SPEC отсутствуют):
/// - одной цифры три раза подряд в теле не бывает → `XXX222XXX` невалиден;
/// - контрольное число проверяется только для номеров **больше** `001-001-998`
///   (нижние не регистрировались): ниже границы чексумма не применяется,
///   структурно корректный номер даёт `Some(true)`. Статус «ниже границы»
///   эталонным вектором §3 не зафиксирован (`#[ignore]` в тестах) — дособрать
///   первичку.
///
/// `None` — не 11 ASCII-цифр.
pub fn snils(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 11 {
        return None;
    }
    // §3 «в номере XXX-XXX-XXX не может быть одной цифры три раза подряд →
    // XXX222XXX невалиден» — НЕВАЛИДЕН только номер, где ОДНА И ТА ЖЕ цифра
    // занимает обе первые группы тела (`222-222-xxx`). Буквальное расширение на
    // «любые три одинаковых подряд» противоречит ВАЛИДН-векторам §3
    // (`480000000 00`, `570000000 00` содержат `000`; `134940005 39` содержит
    // `000` в разрядах 6–8) — зафиксировано #[ignore]-тестом
    // `snils_triple_rule_vector_contradiction`.
    if d[..3] == d[3..6] {
        return Some(false);
    }
    // Контрольное число (следующие строки) §3 проверяет «только для номеров
    // больше 001-001-998»; какие-либо иные вето для нижних номеров документом
    // не заданы. Векторов статуса ниже границы в §3 нет (`#[ignore]`).
    if digits_to_u128(&d[..9]).ok()? <= 1_001_998 {
        return Some(true);
    }
    let control = snils_control(&d[..9])?;
    let stored = u128::from(d[9]) * 10 + u128::from(d[10]);
    Some(u128::from(control) == stored)
}

/// Структурное вето ГРН по первичке —
/// [§4](../../../docs/dep-verify-algorithms.md).
///
/// Первичка: **Приказ Минфина России от 30.10.2017 № 165н**, п.7 Порядка ведения
/// ЕГРЮЛ и ЕГРИП (зарег. Минюстом 16.01.2018 № 49645, ред. на 19.12.2022, метка
/// «Действующий»). Разбор разрядов — `С ГГ КК Х…Х Ч`: `С` — 1-й знак,
/// `ГГ` — 2-й/3-й (год), `КК` — 4-й/5-й (код субъекта), `Х…` — номер записи,
/// `Ч` — контрольное число.
///
/// Вето покрывает ровно два инварианта п.7, сформулированных в первичке как
/// замкнутые перечисления:
///
/// 1. **признак `С` по длине.** 13-значный (ЕГРЮЛ) — `С ∈ {1, 5}` (ОГРН) ∪
///    `{2, 6, 7, 8, 9}` (ГРН-запись ЕГРЮЛ); 15-значный (ЕГРИП) — `С ∈ {3, 4}`
///    (`3` — ОГРНИП, `4` — запись ЕГРИП). Дословно: «к ОГРН - 1, 5; к ОГРНИП -
///    3; к ГРН - 2, 6, 7, 8, 9 (для ЕГРЮЛ), 4 (для ЕГРИП)». Отсюда `3`/`4` в
///    13-значном и `1`/`2`/`5`/`6`/`7`/`8`/`9` в 15-значном невозможны.
/// 2. **`КК ≠ 00`.** Дословно: «кодовое обозначение субъекта Российской
///    Федерации, установленное ФНС России». Первичный срез селектора ФНС
///    (`www.nalog.gov.ru/rn77/search/?text=разряд+ОГРН`) перечисляет коды
///    32…95, «00» среди них нет → «00» обозначением не является.
///
/// Почему вето только по «00», а не по полному перечню ОККОД: сам перечень в
/// п.7 165н не приведён (там только отсылка «установленное ФНС России»), ведётся
/// ФНС отдельно и правится, а наша копия стала бы непроверяемым вторичником —
/// ровно тем классом дефекта, против которого AGENTS §Дисциплина фактов п.1.
/// Всё, что не «00», доверяется чексумме: ложный FP здесь дешевле расхождения с
/// живым реестром, а FN не порождает: номер остаётся классом ОГРН и экранируется.
///
/// `ГГ` и `Х…` вето НЕ покрывает: п.7 не даёт для них замкнутого ограничения
/// (год — «две последние цифры» без диапазона, номер записи — без верхней
/// границы), а `ГГ` исторически не обязан быть ≥ 18 — оговорка про дорелизный
/// `С = 4` в §4.
///
/// Паники нет ни на одном входе: ветка по `len` отрабатывает раньше любого
/// индексирования дальше 4-го разряда.
fn ogrn_structure_ok(d: &[u8]) -> bool {
    let (sign, region) = match d.len() {
        13 | 15 => (d[0], [d[3], d[4]]),
        // Вызывающие (`ogrn13`/`ogrnip15`) проверяют длину до вызова; чужая
        // длина — «не наш класс», а не отказ, но и сюда дойти нельзя.
        _ => return false,
    };
    let sign_ok = match d.len() {
        13 => matches!(sign, 1 | 2 | 5 | 6 | 7 | 8 | 9),
        _ => matches!(sign, 3 | 4),
    };
    sign_ok && region != [0, 0]
}

/// Проверка ОГРН (13 цифр).
///
/// Формула — [§4](../../../docs/dep-verify-algorithms.md): 12 первых цифр как
/// число → `mod 11` → младшая цифра остатка = 13-я. «×4 %10» из SPEC — артефакт
/// пересказа (§4), не реализуется. Модуль 11 теперь подтверждён и первичкой
/// дословно: «младший разряд остатка от деления предыдущего соответственно
/// 12-значного числа на 11 (для ЕГРЮЛ)» — п.7 Приказа Минфина от 30.10.2017
/// № 165н.
///
/// Первичка по номеру акта **закрыта** (было «не найдено», §4 / SPEC §11 п.6):
/// 165н, п.7. Хвост `egrul-refseq` остаётся недоступным из верификационной
/// сессии, но содержание п.7 его больше не блокирует.
///
/// Перед чексуммой действует структурное вето [`ogrn_structure_ok`]:
/// `Some(false)` без обращения к моду 11, если `С` не принадлежит длине или
/// `КК == 00`. Семантика как у остальных структурных проверок модуля: строка
/// остаётся номером нашего класса (каскад-0 её не выбрасывает), просто
/// невалидна; паники нет.
///
/// `None` — не 13 ASCII-цифр.
pub fn ogrn13(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 13 {
        return None;
    }
    if !ogrn_structure_ok(&d) {
        return Some(false);
    }
    let body = digits_to_u128(&d[..12]).ok()?;
    Some(last_digit_of_mod(body, 11) == d[12])
}

/// Проверка ОГРНИП (15 цифр, ИП).
///
/// Формула — [§4](../../../docs/dep-verify-algorithms.md): 14 первых цифр как
/// число → **`mod 13`** → младшая цифра остатка = 15-я. Вердикт §4: SPEC-вариант
/// mod 11 **опровергнут** замером (mod 13 → 3/3, mod 11 → 1/3 на реальных
/// номерах; `313132804400022` и `314220119000137` mod 11 ломает). Модуль 13
/// теперь подтверждён первичкой дословно: «…либо 14-значного числа на 13 (для
/// ЕГРИП)» — п.7 Приказа Минфина от 30.10.2017 № 165н.
/// «Модуль различается по длине, не по типу» — 13 цифр → 11, 15 → 13; отсюда
/// раздельные [`ogrn13`]/[`ogrnip15`] (предохранитель §4).
///
/// Первичка по номеру акта — как у [`ogrn13`] (165н, п.7); вторичник
/// `kdmatrosov/validation-codes` `checkOgrnip.js` (MIT) остаётся сходящимся.
///
/// Структурное вето [`ogrn_structure_ok`]: здесь `С ∈ {3, 4}` — то есть
/// ОГРНИП (`3`) и запись ЕГРИП (`4`), плюс `КК ≠ 00`.
///
/// `None` — не 15 ASCII-цифр.
pub fn ogrnip15(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 15 {
        return None;
    }
    if !ogrn_structure_ok(&d) {
        return Some(false);
    }
    let body = digits_to_u128(&d[..14]).ok()?;
    Some(last_digit_of_mod(body, 13) == d[14])
}

/// Сумма Луны (mod-10 «double-add-double») по цифрам `0..9`.
///
/// Фазировка — [§5b](../../../docs/dep-verify-algorithms.md): удваиваем 2-ю,
/// 4-ю … **справа** (`i % 2 == 1` в обратном обходе); сдвиг фазы «работает на
/// Visa, ломает Mastercard» — воспроизведено при верификации на
/// `5555555555554444`.
fn luhn_sum(digits: &[u8]) -> u32 {
    core::iter::zip(digits.iter().rev(), 0u32..)
        .map(|(&x, i)| {
            // `digits` хранит значения цифр 0..9 (после `ascii_digits`),
            // повторного вычитания `b'0'` здесь быть не должно.
            let mut v = u32::from(x);
            if i % 2 == 1 {
                v *= 2;
                if v > 9 {
                    v -= 9;
                }
            }
            v
        })
        .sum()
}

#[cfg(test)]
/// Тот же обход, но над ASCII-байтами (для adversarial-тестов, которые не
/// проходят через `ascii_digits`).
fn luhn_sum_ascii(digits: &[u8]) -> u32 {
    luhn_sum(
        digits
            .iter()
            .map(|b| b - b'0')
            .collect::<Vec<u8>>()
            .as_slice(),
    )
}

/// Проверка контрольной цифры номера банковской карты (Луна).
///
/// Стандарт — **ISO/IEC 7812-1:2017** (не «7812» целиком: часть 1 — нумерация
/// эмитентов; §5b), алгоритм — §5b, длина тела 12..19 цифр (§5b).
///
/// «Мир»: SPEC-сужение BIN до 2200–2204 **опровергнуто** (§5a: правила НСПК
/// v4.4 диапазон не публикуют; 35/45 наблюдаемых BIN вне ядра = 78 % эмиссии
/// мимо). Валидность здесь — только Луна + длина; BIN — подсказка типа
/// ([`mir_bin`]), не фильтр (§5a: «не понижать приоритет из-за BIN»).
///
/// `None` — не 12..19 ASCII-цифр.
pub fn luhn(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() < 12 || d.len() > 19 {
        return None;
    }
    Some(luhn_sum(&d) % 10 == 0)
}

/// Hint-предикат «номер из блока ПС „Мир“» по первым 6 цифрам (BIN).
///
/// [§5a](../../../docs/dep-verify-algorithms.md): `220000..=229999` — весь
/// выделенный ISIN-блок (вердикт вместо SPEC-«2200–2204»);
/// `67xxxx` — исторические/зарплатные серии, помечены в §5a как `[claim]`
/// (первичкой не подтверждены) — включены по рекомендации документа,
/// классифицировать как «Мир» по ним можно, отбрасывать по ним нельзя.
/// Используется только для типа/приоритета, никогда как фильтр выбрасывания.
///
/// `None` — не 6 ASCII-цифр.
pub fn mir_bin(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 6 {
        return None;
    }
    let v = digits_to_u128(&d).ok()?;
    Some(
        (220_000..=229_999).contains(&u32::try_from(v).ok()?)
            || (670_000..=679_999).contains(&u32::try_from(v).ok()?),
    )
}

/// Строка реестра форматов IBAN: точная длина + маска BBAN.
#[derive(Debug, Clone, Copy)]
struct IbanFormat {
    /// Полная длина IBAN (Registry: «IBAN length»).
    len: usize,
    /// Группы маски BBAN по ISO 13616: `9!n 5!n 15!c` → `[(9,'n'),(5,'n'),(15,'c')]`
    /// в виде закодированных пар (класс: `n` — цифра, `c` — `[A-Z0-9]`,
    /// `a` — буква).
    groups: &'static [(usize, char)],
}

/// Подмножество IBAN REGISTRY (SWIFT, Release 99, Dec 2024), закрытое
/// эталонными векторами §6 + официальным примером EBS204 (§6a–§6b):
/// DE=22, FR=27, **RU=33** (§6a: RU2!n 9!n 5!n 15!c, effective Apr-23),
/// BE=16, NL=18, GB=22.
///
/// Таблицу расширять **только** строками реестра: без проверки длины по стране
/// «DE89…01300» (21 символ) даёт мусор вместо отказа (§6b, правило 1).
const IBAN_REGISTRY: [(&str, IbanFormat); 6] = [
    (
        "RU",
        IbanFormat {
            len: 33,
            groups: &[(9, 'n'), (5, 'n'), (15, 'c')],
        },
    ),
    (
        "DE",
        IbanFormat {
            len: 22,
            groups: &[(18, 'n')],
        },
    ),
    (
        "FR",
        IbanFormat {
            len: 27,
            groups: &[(23, 'c')],
        },
    ),
    (
        "BE",
        IbanFormat {
            len: 16,
            groups: &[(12, 'n')],
        },
    ),
    (
        "NL",
        IbanFormat {
            len: 18,
            groups: &[(4, 'a'), (10, 'n')],
        },
    ),
    (
        "GB",
        IbanFormat {
            len: 22,
            groups: &[(4, 'a'), (14, 'n')],
        },
    ),
];

/// Проверка маски BBAN по группам реестра.
///
/// Ловушка §6a: `15!c` в RU — позиция валюты допускает **букву**; жёсткий
/// `\d` на всех 29 позициях BBAN ломает RU.
fn bban_matches(groups: &[(usize, char)], bban: &[u8]) -> bool {
    let mut pos = 0usize;
    for &(len, class) in groups {
        let end = pos + len;
        if end > bban.len() {
            return false;
        }
        for &b in &bban[pos..end] {
            let ok = match class {
                'n' => b.is_ascii_digit(),
                'c' => b.is_ascii_alphanumeric(),
                'a' => b.is_ascii_alphabetic(),
                _ => false,
            };
            if !ok {
                return false;
            }
        }
        pos = end;
    }
    pos == bban.len()
}

/// Нормализация IBAN: пропуски пробелов/дефисов, верхний регистр; `None` при
/// посторонних символах.
fn iban_normalize(input: &[u8]) -> Option<Vec<u8>> {
    let mut out = Vec::with_capacity(input.len());
    for &b in input {
        if b == b' ' || b == b'-' {
            continue;
        }
        if b.is_ascii_alphanumeric() {
            out.push(b.to_ascii_uppercase());
        } else {
            return None;
        }
    }
    Some(out)
}

/// Степени 10 до 10^9 (длина чанка ≤ 9); табличнее, чем `pow` с приведением —
/// без `usize → u32` и без ветки «не влезло».
fn pow10(n: usize) -> u64 {
    static P: [u64; 10] = [
        1,
        10,
        100,
        1_000,
        10_000,
        100_000,
        1_000_000,
        10_000_000,
        100_000_000,
        1_000_000_000,
    ];
    P[n.min(9)]
}

/// `mod 97` по ISO 7064 над rearranged+cyrillized потоком IBAN.
///
/// Свёртка без big-int: цифры накапливаются в `acc` не более чем по 9 за шаг,
/// `rem = (rem·10^k + acc) mod 97` (§6b: «для general-case берите `BigUint` или
/// piecewise-цикл по 9 цифр»). Буква даёт **две** цифры (A=10…Z=35, §6b шаг 2).
fn iban_mod97(letters_and_digits: &[u8]) -> Option<u32> {
    // Поток цифр (буква = два разряда, §6b шаг 2) режем чанками ровно по 9
    // разрядов: `acc < 1e9`, `rem < 97`, поэтому свёртка `rem·10^k + acc`
    // считается в u64 без переполнения (в u32 — переполнялась: 97·10^9 > u32::MAX;
    // воспроизведено тестом `iban_mod97_matches_doc_column`).
    let mut digits = Vec::with_capacity(letters_and_digits.len() + 8);
    for &b in letters_and_digits {
        if b.is_ascii_digit() {
            digits.push(b - b'0');
        } else {
            let v = u32::from(b) - 55; // A=10 … Z=35 (§6b шаг 2)
            digits.push(u8::try_from(v / 10).unwrap_or_default());
            digits.push(u8::try_from(v % 10).unwrap_or_default());
        }
    }
    let mut rem: u64 = 0;
    for chunk in digits.chunks(9) {
        let mut acc: u64 = 0;
        for &d in chunk {
            acc = acc * 10 + u64::from(d);
        }
        rem = (rem * pow10(chunk.len()) + acc) % 97;
    }
    u32::try_from(rem).ok()
}

/// Проверка IBAN (ISO 13616 / ECBS EBS204 V3 §6.1, mod-97-10).
///
/// Алгоритм — [§6b](../../../docs/dep-verify-algorithms.md): длина и маска по
/// реестру **до** чек-цифры (§6b правила 1–2: mod-97 не вылавливает
/// перестановки пар цифр), затем `t = s[4..]+s[..4]`, буквы→цифры `A=10…Z=35`,
/// `t mod 97 == 1`.
///
/// Первичка: **IBAN REGISTRY**, Registration Authority for ISO 13616 — SWIFT
/// SCRL, Release 99 (Dec 2024), §2.71 «RU – Russia» (33, BBAN `9!n 5!n 15!c`,
/// effective Apr-23): **российский IBAN существует** — SPEC-утверждение «в РФ IBAN
/// нет» опровергнуто (§6a). Алгоритм: ECBS **EBS204 V3, February 2001** §6;
/// текущий стандарт — ISO 13616-1:2020.
///
/// `None` — синтаксис не IBAN: не альфанум, неизвестная (не покрытая таблицей)
/// страна, чужая длина.
pub fn iban(input: &[u8]) -> Option<bool> {
    let s = iban_normalize(input)?;
    if s.len() < 6 {
        return None;
    }
    if !s[..2].iter().all(u8::is_ascii_alphabetic) || !s[2..4].iter().all(u8::is_ascii_digit) {
        return None;
    }
    let cc = core::str::from_utf8(&s[..2]).ok()?;
    let fmt = IBAN_REGISTRY.iter().find(|(c, _)| *c == cc)?.1;
    if s.len() != fmt.len || !bban_matches(fmt.groups, &s[4..]) {
        return None;
    }
    let rearranged: Vec<u8> = s[4..].iter().chain(s[..4].iter()).copied().collect();
    Some(iban_mod97(&rearranged) == Some(1))
}

/// Проверка **структуры** БИК (9 цифр, `04` в начале). Контрольной цифры у БИК
/// нет — это не чексумма, а формат-валидатор.
///
/// [§7b](../../../docs/dep-verify-algorithms.md): в полном тексте Положения
/// Банка России **от 19.06.2012 № 383-П** (зарегистрировано Минюстом
/// 22.06.2012 № 24667; SPEC-номер «385-П/2020» опровергнут — §7a) БИК
/// упоминается только как реквизит «в соответствии со Справочником БИК России»;
/// «никакого алгоритма контрольного разряда документ не определяет».
/// Офлайн-реестра ЦБ нет → проверяем структуру: `^\d{9}$` + `04` в начале (§7b).
///
/// Нереализовано сознательно: проверка ТОКЕН-разрядов (`00…20/78`) и
/// `last3 ≥ 50` — из вторичника, «НЕ подтверждено первичкой, помечаем
/// [claim-unverified]» (§7b); спец-значения `000/001/002` последних трёх —
/// валидны (§7b), отдельного вето на них нет.
///
/// Ловушка §7a: `040106…` — номер формы платёжки по ОКУД из 383-П, **не БИК**;
/// по структуре это 9 цифр с `04` — различение за словарным модулем
/// ([`dictionary`][super::dictionary]), не здесь.
///
/// `None` — не 9 ASCII-цифр.
pub fn bik_format(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 9 {
        return None;
    }
    Some(d[0] == 0 && d[1] == 4)
}

/// Префиксы расчётных счетов, подтверждённые таблицей §7
/// (`30101` корр. счёт банка в ЦБ, `30102` корр. субсчёт — «добавить, в SPEC
/// нет», `3011x`/`40xxx`/`42xxx`/`50xxx` по группе первой пары). Полная таблица
/// Плана счетов — Положение Банка России от 27.02.2017 **№ 579-П**, «первичка не
/// найдена» (§7a; в Викитеке только преамбула, `40702`/`40817`/`30101` не
/// встречаются) — TODO: дособрать.
const ACCOUNT_PREFIXES: [&[u8]; 4] = [b"3010", b"3011", b"40", b"42"];

/// `d` (цифры 0..9) начинается с ASCII-префикса `prefix`.
fn starts_with_digits(d: &[u8], prefix: &[u8]) -> bool {
    d.len() >= prefix.len() && core::iter::zip(d, prefix).all(|(&x, &p)| x == p - b'0')
}

/// Проверка **структуры** 20-значного номера счёта. Чексуммы счёта нет (§7b);
/// проверяем формат + префикс счёта первого порядка (§7 «Что реально проверяемо
/// в каскаде-0»: `^\d{20}$` + префикс-классы).
///
/// Первичка плана счетов — 579-П, полная таблица недоступна (§7a); префиксы
/// ниже взяты из эталонной таблицы §7 и перекрёстно подтверждены реестром SWIFT
/// (§7a: BBAN-пример RU содержит раздел корсчёта `40817`).
///
/// `None` — не 20 ASCII-цифр.
pub fn bank_account_format(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 20 {
        return None;
    }
    // Сравнение по цифрам (без реконструкции строки): префикс-классы заданы
    // десятичными цифрами, `d` уже содержит значения 0..9.
    Some(ACCOUNT_PREFIXES.iter().any(|p| starts_with_digits(&d, p)))
}

/// Дешёвый перекрёстный фильтр пары БИК ↔ счёт (§7 «Что реально проверяемо»):
/// совпадение регионального кода БИК и 7–8 разрядов счёта.
///
/// Индексация — ровно как в §7: «`БИК[1:3] == счёт[6:8]` (совпадение региона
/// БИК и 7–8 разрядов номера счёта)» — полуоткрытые 0-based срезы.
/// `None` — чужие длины/не цифры; `Some(false)` — несовпадение (кандидат в FP).
pub fn bik_account_cross(bik: &[u8], account: &[u8]) -> Option<bool> {
    if bik.len() != 9 || account.len() != 20 {
        return None;
    }
    if !bik.iter().all(u8::is_ascii_digit) || !account.iter().all(u8::is_ascii_digit) {
        return None;
    }
    Some(bik[1..3] == account[6..8])
}

