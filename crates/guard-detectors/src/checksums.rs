/// Проверка маски BBAN по строке реестра (`"9n5n15c"`).
///
/// Ловушка §6a: `15!c` в RU — позиция валюты допускает **букву**; жёсткий
/// `\d` на всех 29 позициях BBAN ломает RU.
///
/// Парсер маски — цикл без аллокаций: серия цифр = длина группы, следующая
/// буква = класс группы; мусор в строке маски = `false` (таблица константная,
/// так что это защита от правки, а не от ввода).
fn bban_matches(mask: &str, bban: &[u8]) -> bool {
    let m = mask.as_bytes();
    let mut i = 0usize;
    let mut pos = 0usize;
    while i < m.len() {
        let mut n = 0usize;
        while i < m.len() && m[i].is_ascii_digit() {
            n = n * 10 + usize::from(m[i] - b'0');
            i += 1;
        }
        let Some(&class) = m.get(i) else {
            return false;
        };
        i += 1;
        let end = pos + n;
        if end > bban.len() {
            return false;
        }
        for &b in &bban[pos..end] {
            let ok = match class {
                b'n' => b.is_ascii_digit(),
                b'c' => b.is_ascii_alphanumeric(),
                b'a' => b.is_ascii_alphabetic(),
                _ => false,
            };
            if !ok {
                return false;
            }
        }
        pos = end;
    }
    pos == bban.len()
}

/// Разделители, которые терпит **номер внутри себя**: печатная форма IBAN
/// разбивает номер группами по 4 (`RU03 0445 2522 …`), СНИЛС печатают
/// `378-312-074 87`, карту — `2204-9947-4132-9761`; в кириллических и CJK
/// вставках вместо ASCII-дефиса встречается типографский.
///
/// Список публичный: каскад 0 строит по нему окна сканера
/// (`guard_daemon::cascade0::num_runs`), валидатор по нему же канонизирует
/// вход — два владельца одного перечня неизбежно разъехались бы.
pub const NUMBER_SEPARATORS: &[&[u8]] = &[
    b" ",                  // U+0020 (нормализатор сводит к нему все Zs, включая NBSP)
    b"-",                  // U+002D HYPHEN-MINUS
    "\u{2010}".as_bytes(), // U+2010 HYPHEN
    "\u{2011}".as_bytes(), // U+2011 NON-BREAKING HYPHEN
    "\u{2012}".as_bytes(), // U+2012 FIGURE DASH
    "\u{FF0D}".as_bytes(), // U+FF0D FULLWIDTH HYPHEN-MINUS
];

/// Нормализация IBAN: пропуски разделителей ([`NUMBER_SEPARATORS`]), верхний
/// регистр; `None` при посторонних символах.
fn iban_normalize(input: &[u8]) -> Option<Vec<u8>> {
    let mut out = Vec::with_capacity(input.len());
    let mut i = 0usize;
    while i < input.len() {
        if let Some(sep) = NUMBER_SEPARATORS.iter().find(|s| input[i..].starts_with(s)) {
            i += sep.len();
            continue;
        }
        let b = input[i];
        if b.is_ascii_alphanumeric() {
            out.push(b.to_ascii_uppercase());
            i += 1;
        } else {
            return None;
        }
    }
    Some(out)
}

/// Степени 10 до 10^9 (длина чанка ≤ 9); табличнее, чем `pow` с приведением —
/// без `usize → u32` и без ветки «не влезло».
fn pow10(n: usize) -> u64 {
    static P: [u64; 10] = [
        1,
        10,
        100,
        1_000,
        10_000,
        100_000,
        1_000_000,
        10_000_000,
        100_000_000,
        1_000_000_000,
    ];
    P[n.min(9)]
}

/// `mod 97` по ISO 7064 над rearranged+cyrillized потоком IBAN.
///
/// Свёртка без big-int: цифры накапливаются в `acc` не более чем по 9 за шаг,
/// `rem = (rem·10^k + acc) mod 97` (§6b: «для general-case берите `BigUint` или
/// piecewise-цикл по 9 цифр»). Буква даёт **две** цифры (A=10…Z=35, §6b шаг 2).
fn iban_mod97(letters_and_digits: &[u8]) -> Option<u32> {
    // Поток цифр (буква = два разряда, §6b шаг 2) режем чанками ровно по 9
    // разрядов: `acc < 1e9`, `rem < 97`, поэтому свёртка `rem·10^k + acc`
    // считается в u64 без переполнения (в u32 — переполнялась: 97·10^9 > u32::MAX;
    // воспроизведено тестом `iban_mod97_matches_doc_column`).
    let mut digits = Vec::with_capacity(letters_and_digits.len() + 8);
    for &b in letters_and_digits {
        if b.is_ascii_digit() {
            digits.push(b - b'0');
        } else {
            let v = u32::from(b) - 55; // A=10 … Z=35 (§6b шаг 2)
            digits.push(u8::try_from(v / 10).unwrap_or_default());
            digits.push(u8::try_from(v % 10).unwrap_or_default());
        }
    }
    let mut rem: u64 = 0;
    for chunk in digits.chunks(9) {
        let mut acc: u64 = 0;
        for &d in chunk {
            acc = acc * 10 + u64::from(d);
        }
        rem = (rem * pow10(chunk.len()) + acc) % 97;
    }
    u32::try_from(rem).ok()
}

/// Проверка IBAN (ISO 13616 / ECBS EBS204 V3 §6.1, mod-97-10).
///
/// Алгоритм — [§6b](../../../docs/dep-verify-algorithms.md): длина и маска по
/// реестру **до** чек-цифры (§6b правила 1–2: mod-97 не вылавливает
/// перестановки пар цифр), затем `t = s[4..]+s[..4]`, буквы→цифры `A=10…Z=35`,
/// `t mod 97 == 1`.
///
/// Первичка: **IBAN REGISTRY**, Registration Authority for ISO 13616 — SWIFT
/// SCRL, Release 99 (Dec 2024), §2.71 «RU – Russia» (33, BBAN `9!n 5!n 15!c`,
/// effective Apr-23): **российский IBAN существует** — SPEC-утверждение «в РФ IBAN
/// нет» опровергнуто (§6a). Алгоритм: ECBS **EBS204 V3, February 2001** §6;
/// текущий стандарт — ISO 13616-1:2020.
///
/// `None` — синтаксис не IBAN: не альфанум, неизвестная (не покрытая таблицей)
/// страна, чужая длина.
pub fn iban(input: &[u8]) -> Option<bool> {
    let s = iban_normalize(input)?;
    if s.len() < 6 {
        return None;
    }
    if !s[..2].iter().all(u8::is_ascii_alphabetic) || !s[2..4].iter().all(u8::is_ascii_digit) {
        return None;
    }
    let cc = core::str::from_utf8(&s[..2]).ok()?;
    let fmt = IBAN_REGISTRY.iter().find(|(c, _)| *c == cc)?.1;
    if s.len() != fmt.len || !bban_matches(fmt.mask, &s[4..]) {
        return None;
    }
    let rearranged: Vec<u8> = s[4..].iter().chain(s[..4].iter()).copied().collect();
    Some(iban_mod97(&rearranged) == Some(1))
}

/// Проверка **структуры** БИК (9 цифр, `04` в начале). Контрольной цифры у БИК
/// нет — это не чексумма, а формат-валидатор.
///
/// [§7b](../../../docs/dep-verify-algorithms.md): в полном тексте Положения
/// Банка России **от 19.06.2012 № 383-П** (зарегистрировано Минюстом
/// 22.06.2012 № 24667; SPEC-номер «385-П/2020» опровергнут — §7a) БИК
/// упоминается только как реквизит «в соответствии со Справочником БИК России»;
/// «никакого алгоритма контрольного разряда документ не определяет».
/// Офлайн-реестра ЦБ нет → проверяем структуру: `^\d{9}$` + `04` в начале (§7b).
///
/// Нереализовано сознательно: проверка ТОКЕН-разрядов (`00…20/78`) и
/// `last3 ≥ 50` — из вторичника, «НЕ подтверждено первичкой, помечаем
/// [claim-unverified]» (§7b); спец-значения `000/001/002` последних трёх —
/// валидны (§7b), отдельного вето на них нет.
///
/// Ловушка §7a: `040106…` — номер формы платёжки по ОКУД из 383-П, **не БИК**;
/// по структуре это 9 цифр с `04` — различение за словарным модулем
/// ([`dictionary`][super::dictionary]), не здесь.
///
/// `None` — не 9 ASCII-цифр.
pub fn bik_format(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 9 {
        return None;
    }
    Some(d[0] == 0 && d[1] == 4)
}

/// Префиксы расчётных счетов, подтверждённые таблицей §7
/// (`30101` корр. счёт банка в ЦБ, `30102` корр. субсчёт — «добавить, в SPEC
/// нет», `3011x`/`40xxx`/`42xxx`/`50xxx` по группе первой пары). Полная таблица
/// Плана счетов — **№ 579-П отменён с 01.01.2023** (п.3 Положения ЦБ от
/// 24.11.2022 № 809-П), носитель таблицы теперь 809-П; полная таблица не
/// собрана (§7a: в Викитеке только преамбула 579-П, `40702`/`40817`/`30101` не
/// встречаются; PDF 809-П с `cbr.ru` мост сессии не сохраняет) — TODO: дособрать.
const ACCOUNT_PREFIXES: [&[u8]; 4] = [b"3010", b"3011", b"40", b"42"];

/// `d` (цифры 0..9) начинается с ASCII-префикса `prefix`.
fn starts_with_digits(d: &[u8], prefix: &[u8]) -> bool {
    d.len() >= prefix.len() && core::iter::zip(d, prefix).all(|(&x, &p)| x == p - b'0')
}

/// Проверка **структуры** 20-значного номера счёта. Чексуммы счёта нет (§7b);
/// проверяем формат + префикс счёта первого порядка (§7 «Что реально проверяемо
/// в каскаде-0»: `^\d{20}$` + префикс-классы).
///
/// Первичка плана счетов — 809-П (пришёл на смену 579-П), полная таблица не
/// собрана (§7a); префиксы
/// ниже взяты из эталонной таблицы §7 и перекрёстно подтверждены реестром SWIFT
/// (§7a: BBAN-пример RU содержит раздел корсчёта `40817`).
///
/// `None` — не 20 ASCII-цифр.
pub fn bank_account_format(input: &[u8]) -> Option<bool> {
    let d = ascii_digits(input)?;
    if d.len() != 20 {
        return None;
    }
    // Сравнение по цифрам (без реконструкции строки): префикс-классы заданы
    // десятичными цифрами, `d` уже содержит значения 0..9.
    Some(ACCOUNT_PREFIXES.iter().any(|p| starts_with_digits(&d, p)))
}

/// Дешёвый перекрёстный фильтр пары БИК ↔ счёт (§7 «Что реально проверяемо»):
/// совпадение регионального кода БИК и 7–8 разрядов счёта.
///
/// Индексация — ровно как в §7: «`БИК[1:3] == счёт[6:8]` (совпадение региона
/// БИК и 7–8 разрядов номера счёта)» — полуоткрытые 0-based срезы.
/// `None` — чужие длины/не цифры; `Some(false)` — несовпадение (кандидат в FP).
pub fn bik_account_cross(bik: &[u8], account: &[u8]) -> Option<bool> {
    if bik.len() != 9 || account.len() != 20 {
        return None;
    }
    if !bik.iter().all(u8::is_ascii_digit) || !account.iter().all(u8::is_ascii_digit) {
        return None;
    }
    Some(bik[1..3] == account[6..8])
}

