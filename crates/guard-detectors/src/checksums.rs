    /// Самоконтроль таблицы: сумма длин групп маски обязана равняться
    /// `len - 4`, маска состоять из пар «число + n/c/a». Ловит опечатку при
    /// ручном расширении таблицы — а расширять её, по док-правилу, можно только
    /// строками реестра.
    #[test]
    fn iban_table_masks_are_self_consistent() {
        for (cc, f) in IBAN_REGISTRY {
            let m = f.mask.as_bytes();
            let mut i = 0usize;
            let mut sum = 0usize;
            while i < m.len() {
                let mut n = 0usize;
                while i < m.len() && m[i].is_ascii_digit() {
                    n = n * 10 + usize::from(m[i] - b'0');
                    i += 1;
                }
                assert!(
                    matches!(m.get(i), Some(b'n' | b'c' | b'a')),
                    "{cc}: мусор в маске {:?}",
                    f.mask
                );
                i += 1;
                sum += n;
            }
            assert_eq!(
                sum,
                f.len - 4,
                "{cc}: маска {:?} не сходится с длиной {}",
                f.mask,
                f.len
            );
        }
    }

