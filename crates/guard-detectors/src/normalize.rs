//! Каскад 0, стадия нормализации (SPEC §6: `normalizer(OffsetMap)`; SPEC §10 п.3;
//! требование property-тестов — SPEC §9 «property-тесты `OffsetMap` на рваной
//! кириллице»).
//!
//! [`normalize`] приводит вход к канонической форме, «разрывной» для детекторов
//! (разрывы внутри номерков, fullwidth-цифры/буквы, кириллические комбайнинг-
//! марки), и возвращает [`OffsetMap`] — карту «offset в нормализованном тексте →
//! offset в исходном». Все последующие детекторы (checksums / secrets /
//! dictionary) обязаны конвертировать свои спаны через
//! [`OffsetMap::map_span_to_original`], чтобы в ответы наружу уходили координаты
//! **исходного** текста (порядок модулей в `lib.rs`).
//!
//! ## API
//!
//! - единственный содержательный конструктор — [`OffsetMap::build`]: пара
//!   `(Cow<str>, OffsetMap)`; `Cow::Borrowed` при identity (ни одного
//!   сработавшего правила), `Cow::Owned` иначе;
//! - [`OffsetMap::map_to_original`] возвращает `Option<usize>` (имя из ТЗ
//!   атома): вне `[0, normalized_len]` карты нет; молча климпить границу —
//!   значит врать вызывающему, который соберёт спан над чужим текстом;
//! - [`OffsetMap::default`] — identity-карта на пустом входе, совместимость с
//!   каркасом шага 1.
//!
//! ## Почему свой узкий набор правил, а не `unicode-normalization`
//!
//! `unicode-normalization` отсутствует в `[workspace.dependencies]` (промер
//! `Cargo.toml` в этом же заходе), а AGENTS §Дисциплина фактов п.2 запрещает код
//! с непроверенными зависимостями — добавление крейта требует отдельного промера
//! и рулинга. Реализовано целевое подмножество NFKC-подобных правил — ровно то,
//! что нужно каскаду 0 для PII-номерков; точный перечень непокрытого — в
//! [`rules_todo`].
//!
//! ## Инварианты [`OffsetMap`] (покрыты property-тестами, `mod proptests`)
//!
//! 1. монотонность непрерывная: `p1 < p2 ⟹ o1 ≤ o2`;
//! 2. каждый маппящий offset — валидная UTF-8-граница исходного текста;
//! 3. span-consistency (round-trip): [`OffsetMap::original_for`] возвращает
//!    оригинальный substring, нормализация которого равна нормализованному
//!    substring (сама переклейка — проверяемая часть инварианта);
//! 4. на входе без срабатываний правил — `is_identity()` и `Cow::Borrowed`;
//! 5. пустой вход → пустая карта, без паник;
//! 6. идемпотентность текста: `normalize(normalize(x)).0 == normalize(x).0` и
//!    вторая карта identity (property-тест `idempotence_text`; правила
//!    поточечные, без look-ahead, поэтому второй прогон ничего не находит).

use std::borrow::Cow;
use std::ops::Range;

use guard_types::ByteSpan;

/// ## Склейки разрывов между цифрами НЕТ (рулинг атома step3a, 19.10)
///
/// Черновик нормализатора склеивал `1-2` → `12` (константа `MAX_GLUE_CHAIN`,
/// предикат `is_digit_separator`). Ревизия отвергла это правило: схлопывание
/// разделителей внутри цифровых последовательностей рождает ложноположительные
/// ИНН/СНИЛС внутри обычных фраз («в 12 часов и 34 минуты» → `1234`), а FP
/// каскада-0 умножаются на все 4 каскада. Толерантность к разрывам — обязанность
/// regex-слоя детектора (`[\s-]*` в позиции разделителя), не нормализатора.
/// Первичная проверка по факту (golden-v1.jsonl, 200 строк, промер в этом
/// заходе): все 446 межцифровых разрывов датасета — ОДИНОЧНЫЕ (`' '` 221, `-`
/// 115, `.` 68, `/` 23); многосимвольных групп нет ни одной, zero-width / NBSP
/// / fullwidth / U+0483–U+0487 в датасете — 0 вхождений. Т.е. склейка не нужна
/// даже для recall нашего же golden-набора.
///
/// Zero-width коды, удаляемые в ЛЮБОЙ позиции (рулинг атома, п.2б): коды без
/// собственного графемного смысла в тексте ПДн — BOM на вставке, ZWSP из
/// веб-копий. Промер первичкой (NFKC, Python unicodedata вне дерева, этот
/// заход): `NFKC('\u{200B}') == '\u{200B}'`, `NFKC('\u{FEFF}') == '\u{FEFF}'` —
/// удаление zero-width есть НАШЕ расширение сверх NFKC, а не NFKC-правило;
/// удаление НЕ ограничено позицией «между цифрами»: вне цифр эти коды ровно
/// так же мешают regex-слою и не значат ничего.
const ZERO_WIDTH_REMOVE: &[char] = &['\u{200B}', '\u{200C}', '\u{200D}', '\u{FEFF}'];

/// Возвращает `true`, если `c` — удаляемый zero-width коды.
fn is_zero_width(c: char) -> bool {
    ZERO_WIDTH_REMOVE.contains(&c)
}

/// Пробельные класса `Zs`, которые NFKC сводит к U+0020 (промер первичкой:
/// `\u{A0}` → `' '`, `\u{2000}` → `' '`, `\u{202F}` → `' '`, `\u{3000}` →
/// `' '`; в NFC — остаются как есть). Ревизия атома step3a: это ЕДИНСТВЕННЫЕ
/// пробельные, меняемые нормализатором; склейки по ним нет.
fn nfkc_space_to_ascii(c: char) -> Option<char> {
    matches!(c,
        '\u{A0}' | '\u{2000}'..='\u{200A}' | '\u{202F}' | '\u{205F}' | '\u{3000}'
    )
    .then_some(' ')
}

/// Кириллические комбайнинг-марки, подлежащие удалению.
///
/// Удаляются ТОЛЬКО эти диапазоны:
/// - латинские/греческие `U+0300..=U+036F` остаются нетронутыми (иначе
///   нормализация сломала бы ударные гласные итальянских/испанских имён —
///   ложное изменение данных);
/// - промер UCD 16.0 (unicodedata в сессии прогона, вне дерева проекта): ни
///   одна марка из перечисленных ниже диапазонов **не** канонически компонуется
///   с кириллической базой (0 пар U+0400…U+04FF × наши марки) — удаление марки
///   не создаёт новой компонуемой смежности и не меняет форму остатка.
const CYRILLIC_COMBINING_MARKS: &[(u32, u32)] = &[
    // U+0483…U+0487 — кириллические надстрочные (титло, палатация, дазиа,
    // псили, покрытие). UCD 16.0, категория Mn. Классический источник «рваной
    // кириллицы» OCR-сканов и копипасты церковных текстов; U+0487 = COMBINING
    // CYRILLIC POKRYTIE — кейс SPEC §9 («Ж» + U+0487).
    (0x0483, 0x0487),
    // U+0488…U+0489 — кириллические обведённые литеры (Mn), смыкаются с выше.
    (0x0488, 0x0489),
    // U+20D0…U+20DC, U+20E1, U+20E5…U+20E9 — «combining … above/below» (Mn):
    // точки над, стрелки; прилипают к кириллице из математических и OCR-документов.
    // UCD 16.0, Block U+20D0–U+20FF. U+20DD…U+20E0 и U+20E2…U+20E4 — So
    // (символы, не марки), сознательно вне набора.
    (0x20D0, 0x20DC),
    (0x20E1, 0x20E1),
    (0x20E5, 0x20E9),
    // U+FE20…U+FE23 — половинки лигатур/двойных тилд (Mn), палеографическая
    // кириллица. UCD 16.0, Block U+FE20–U+FE26 (U+FE24…U+FE26 — Mn, но
    // лигатурные хвосты греческие; вне кириллического набора).
    (0xFE20, 0xFE23),
];

/// Возвращает `true`, если `c` — комбайнинг-марка из кириллического набора.
fn is_cyrillic_combining(c: char) -> bool {
    let cp = c as u32;
    CYRILLIC_COMBINING_MARKS
        .iter()
        .any(|&(lo, hi)| cp >= lo && cp <= hi)
}

/// Fullwidth-цифры/латиница → ASCII: один арифметический сдвиг `0xFEE0`, без
/// ICU-таблиц и без `unicode-normalization`.
///
/// Диапазоны (промер UCD 16.0: Nd/Lu/Ll, непрерывные отрезки, разложение ровно
/// `<wide> U+00XX`): `U+FF10…U+FF19` → `0…9`, `U+FF21…U+FF3A` → `A…Z`,
/// `U+FF41…U+FF5A` → `a…z`. Fullwidth-пунктуация/символы (`U+FF01…U+FF0F`,
/// `U+FF1A…U+FF20`, `U+FF3B…U+FF40`, `U+FF5B…U+FF65`, `U+FFE0…U+FFE6`) — вне
/// ТЗ-набора, см. [`rules_todo`] п.1.
fn fullwidth_to_ascii(c: char) -> Option<char> {
    let cp = c as u32;
    let ascii = match cp {
        0xFF10..=0xFF19 | 0xFF21..=0xFF3A | 0xFF41..=0xFF5A => cp - 0xFEE0,
        _ => return None,
    };
    // Результат гарантированно ASCII 0x30..=0x7A — from_u32 не отказывает.
    char::from_u32(ascii)
}

/// Нормализует текст каскада 0 и строит карту смещений (SPEC §2 Каскад 0 —
/// PRE-компонент перед чексуммами/секретами/автоматом).
///
/// Правила:
/// 1. удаление кириллических комбайнинг-марк (SPEC §9 «рваная кириллица»);
/// 2. удаление zero-width кодов [`ZERO_WIDTH_REMOVE`] (U+200B…U+200D, U+FEFF)
///    в любой позиции — расширение сверх NFKC (промер: NFKC их сохраняет);
/// 3. fullwidth-цифры/латиница → ASCII ([`fullwidth_to_ascii`]) и широкие
///    пробельные `Zs` → U+0020 ([`nfkc_space_to_ascii`]) — NBSP → пробел по
///    NFKC; РАЗРЫМЫ МЕЖДУ ЦИФРАМИ НЕ СХЛОПЫВАЮТСЯ (см. док модуля);
/// 4. остальной текст — identity (в т.ч. разделители вне пар «цифра–цифра»,
///    латинские комбайнинг-марки, эмодзи).
///
/// ## Идемпотентность
///
/// Все правила — поточечные замены/удаления по одному символу (без look-ahead),
/// поэтому нормализация ТЕКСТА строго идемпотентна: `normalize(normalize(x)) ==
/// normalize(x)` (инвариант 6). Второй прогон по канонической форме ничего не
/// находит: удалённые марки не возвращаются, fullwidth уже ASCII, пробелы уже
/// U+0020, zero-width уже удалены. Композиция карт вырождается в тривиальную:
/// `map.compose(identity) == map`. Property-тест `idempotence_text` в
/// `mod proptests` проверяет это на случайных входах.
#[must_use]
pub fn normalize(input: &str) -> (Cow<'_, str>, OffsetMap) {
    OffsetMap::build(input)
}

/// Точка перелома карты: байт нормализованного текста → байт исходного.
#[derive(Debug, Clone, Copy, Eq, PartialEq)]
struct Key {
    norm: u32,
    orig: u32,
}

/// Зафиксировать начало изменённого фрагмента (одна точка перелома на фрагмент).
///
/// Соседние срабатывания правил (`Ж\u{487}\u{488}` — две марки подряд,
/// `\u{FF17}\u{FF17}` — две fullwidth-цифры) дают одну и ту же пару
/// `(norm_start, orig_start)`; дедуп по паре (НЕ по `norm`) схлопывает их в
/// один фрагмент. Дедуп по `norm` — ловушка: равноширинная замена NBSP
/// (`orig == norm`, длина 2→2) имеет ту же норм-координату, что и следующая
/// за ней удалённая марка (норм-координата не двигается, пока дельта не
/// появилась), и была бы потеряна.
///
/// `norm == orig` НЕ является основанием для выбрасывания точки: у замены
/// `\u{A0}` → `' '` координаты начала совпадают, но карта без этой точки
/// врала бы о смещении хвоста.
/// Точка перелома карты, если дельта `orig - norm` изменилась.
///
/// Модель карты: `map(p) = p + delta(p)`, где `delta` — кусочно-постоянная
/// функция с конечным числом разрывов; `segs` хранит сами разрывы (`norm` —
/// позиция в норме СРАЗУ ПОСЛЕ скачка, `orig = norm + delta_после`).
/// Прямое следствие: точка нужна РОВНО там, где дельта сменилась, и только
/// когда она ненулевая (`delta == 0` — identity, карта не растёт).
///
/// Почему не «писать на месте срабатывания правила» (дефект черновика, из-за
/// которого падал `debug_assert` конца нормы): у равноширинного удаления
/// (`abc\u{FEFF}def`, BOM стартует при `norm == orig == 3`) точка с нулевой
/// дельтой в ветке `Ok(i)` возвращала `orig` вместо `orig + дельта` — сдвиг
/// хвоста терялся, `map_span(3..6)` давало `(3, 9)` вместо `(6, 9)`.
///
/// Соседние срабатывания (`\u{200B}\u{200C}`, `\u{487}\u{488}`, серия
/// fullwidth-цифр) дают РАЗНЫЕ дельты на каждом шаге — каждая записывается
/// отдельной точкой; это корректно: между ними дельта действительно скачет.
fn note_breakpoint(segs: &mut Vec<Key>, norm_cur: usize, orig_cur: usize) {
    let k = Key { norm: norm_cur as u32, orig: orig_cur as u32 };
    match segs.last_mut() {
        // Тот же норм-курсор — предыдущая точка перезаписывается накопленной
        // дельтой (слияние соседних срабатываний в один фрагмент).
        Some(last) if last.norm == k.norm => *last = k,
        Some(last) if last == &k => {}
        _ => segs.push(k),
    }
}

/// Карта «offset нормализованного текста → offset исходного» (SPEC §6, §10 п.3).
///
/// Хранит начала изменённых фрагментов: `(off_norm, off_orig)` для каждого
/// фрагмента оригинала, изменённого хотя бы одним правилом. Между фрагментами
/// смещение постоянно (межфрагментные участки — identity), поэтому карта —
/// монотонная кусочно-постоянная функция; хвост после последнего фрагмента —
/// identity со сдвигом `len_orig - len_norm`.
///
/// Инварианты (доказаны property-тестами, `mod proptests`): см. док модуля, 1–6.
#[derive(Debug, Clone, Eq, PartialEq)]
pub struct OffsetMap {
    /// Начала изменённых фрагментов: строго монотонны по `norm`, обе координаты
    /// — char-границы соответствующих текстов. Точка может лежать НА самой
    /// границе фрагмента (`orig == norm`, равноширинная замена) или за концом
    /// нормы (хвостовое удаление) — обе нужны для round-trip.
    segs: Vec<Key>,
    /// Хоть одно правило сработало (текст ≠ оригинал). См. [`Self::is_identity`].
    changed: bool,
    len_norm: usize,
    len_orig: usize,
}

impl Default for OffsetMap {
    /// Identity-карта на пустом входе — совместимость с каркасом шага 1.
    fn default() -> Self {
        Self {
            segs: Vec::new(),
            changed: false,
            len_norm: 0,
            len_orig: 0,
        }
    }
}

impl OffsetMap {
    /// Построить нормализованный текст и карту для `original`.
    ///
    /// Однопроходный инкрементальный алгоритм O(n). `Cow::Borrowed` при
    /// identity (инвариант 4), `Cow::Owned` иначе.
    #[must_use]
    pub fn build(original: &str) -> (Cow<'_, str>, Self) {
        let mut norm = String::with_capacity(original.len());
        let mut segs: Vec<Key> = Vec::new();
        let mut changed = false;
        // Идём по оригиналу char за char; `norm.len()` и байт конца последнего
        // обработанного символа оригинала (`orig_end`) — два курсора. Третья
        // величина, дельта `orig_end - norm.len()`, и есть состояние карты.
        let mut orig_end = 0usize;

        // Две оси: `norm.len()` (байт в норме) и `orig_end` (байт в оригинале,
        // конец последнего обработанного символа). Точка перелома пишется на
        // КАЖДОМ шаге, где дельта `orig_end - norm.len()` изменилась относительно
        // предыдущего шага; `segs` — история этих изменений, отсюда
        // `map(p) = p + delta(последняя точка с norm <= p)`.
        let mut orig_end = 0usize;
        let mut prev_delta = 0i64;

        for (i, c) in original.char_indices() {
            debug_assert_eq!(i, orig_end, "курсор оригинала не скачет");
            // -- Правила 1а+2: удаление (комбайнинг-марки, zero-width).
            let out_ch = if is_zero_width(c) || is_cyrillic_combining(c) {
                changed = true;
                None
            } else if let Some(a) = fullwidth_to_ascii(c).or_else(|| nfkc_space_to_ascii(c)) {
                if a != c {
                    changed = true;
                    Some(a)
                } else {
                    Some(c)
                }
            } else {
                Some(c)
            };
            if let Some(a) = out_ch {
                norm.push(a);
            }
            orig_end = i + c.len_utf8();
            let delta = orig_end as i64 - norm.len() as i64;
            if delta != prev_delta {
                note_breakpoint(&mut segs, norm.len(), orig_end);
                prev_delta = delta;
            }
        }
        let _ = orig_end;


        // `Cow::Borrowed` ровно когда ни одно правило не сработало (инвариант 4).
        let out = if changed {
            Cow::Owned(norm)
        } else {
            Cow::Borrowed(original)
        };
        let len_norm = out.len();
        let map = Self {
            segs,
            changed,
            len_norm,
            len_orig: original.len(),
        };
        debug_assert_eq!(
            map.map_to_original(len_norm),
            Some(original.len()),
            "конец нормы обязан маппиться на конец оригинала"
        );
        (out, map)
    }

    /// Длина нормализованного текста в байтах.
    #[must_use]
    pub fn normalized_len(&self) -> usize {
        self.len_norm
    }

    /// Длина исходного текста в байтах.
    #[must_use]
    pub fn original_len(&self) -> usize {
        self.len_orig
    }

    /// `true`, если ни одно правило не сработало: нормализованный текст байт в
    /// байт равен исходному.
    ///
    /// Ключ — НЕ `segs.is_empty()`: равноширинная замена (`\u{A0}` → `' '`)
    /// даёт `orig == norm` и не двигает карту, поэтому «карта пуста» не
    /// эквивалентно «текст цел». Флаг `changed` пишется на каждом срабатывании.
    /// Карты с равным `changed` и пустыми `segs` (identity) не бывает.
    ///
    /// NB: `Default::default()` — identity на пустом входе (`changed = false`).
    #[must_use]
    pub fn is_identity(&self) -> bool {
        !self.changed
    }

    /// Отразить байтовый offset из нормализованного текста в исходный.
    ///
    /// `None` — вне `[0, normalized_len]`. Возврат всегда валидная char-граница
    /// исходного текста (инвариант 2). Offset до первого перелома относится к
    /// identity-префиксу (`orig == norm`), после последнего — identity-хвосту.
    ///
    /// Терминальный инвариант (специальный случай): `pos == normalized_len` —
    /// указатель за конец нормы — маппится ровно на `original_len`, независимо
    /// от того, стоит ли на `normalized_len` начало изменённого фрагмента.
    #[must_use]
    pub fn map_to_original(&self, pos_norm: usize) -> Option<usize> {
        if pos_norm > self.len_norm {
            return None;
        }
        // Терминальный инвариант: указатель за конец нормы маппится ровно на
        // конец оригинала, даже если последняя точка перелома стоит НА конце
        // нормы (хвостовое удаление: `Ж\u{487}` → `Ж`) — иначе round-trip
        // `original_for(0..len)` терял бы хвостовой удалённый фрагмент.
        if pos_norm == self.len_norm {
            return Some(self.len_orig);
        }
        let p = pos_norm as u32;
        // Активна точка с НАИБОЛЬШИМ `k.norm <= p`: дельта действует ПОСЛЕ
        // своего скачка, не до него. `Err(i)` — первая точка строго после `p`,
        // значит активна `i-1` (или дельты нет вовсе).
        let i = match self.segs.binary_search_by_key(&p, |k| k.norm) {
            Ok(i) => i,
            Err(0) => return Some(pos_norm),
            Err(i) => i - 1,
        };
        let k = self.segs[i];
        Some(p as usize - k.norm as usize + k.orig as usize)
    }

    /// Композиция двух карт: `self` — карта первого прогона (оригинал → норма 1),
    /// `other` — карта второго прогона (норма 1 → норма 2). Результат — карта
    /// оригинал → норма 2: точки перелома `other` проображаются через `self`;
    /// точка, у которой прообраз совпал с самой координатой (`orig == norm`),
    /// НЕ добавляется — между точками наклон карты и так единица; соседние
    /// точки с равными парами сливаются ([`begin_segment`]).
    ///
    /// Корректность: `self` кусочно-аффинна с наклоном 1, `other` — тоже,
    /// прообраз точки перелома `other` падает в char-границу оригинала
    /// (инвариант 2), между соседними прообразами дельта постоянна (иначе
    /// какая-то точка `self` лежит между ними — значит она была бы в множестве
    /// прообразов).
    #[must_use]
    pub fn compose(&self, other: &OffsetMap) -> OffsetMap {
        let mut segs: Vec<Key> = Vec::with_capacity(self.segs.len() + other.segs.len());
        for &k in &other.segs {
            if let Some(orig) = self.map_to_original(k.norm as usize) {
                if orig != k.norm as usize {
                    let key = Key { norm: k.norm, orig: orig as u32 };
                    if segs.last() != Some(&key) {
                        segs.push(key);
                    }
                }
            }
        }
        Self {
            segs,
            changed: self.changed | other.changed,
            len_norm: other.len_norm,
            len_orig: self.len_orig,
        }
    }

    /// Композиция карт на уровне точки: `pos` (координата в тексте ВТОРОЙ нормы)
    /// → байт оригинала через `first` (оригинал → норма 1) и `second`
    /// (норма 1 → норма 2). Эквивалентен
    /// `first.compose(second).map_to_original(pos)` (property-тест
    /// `compose_matches_map2`).
    #[must_use]
    pub fn map2(first: &OffsetMap, second: &OffsetMap, pos: usize) -> Option<usize> {
        second
            .map_to_original(pos)
            .and_then(|p1| first.map_to_original(p1))
    }

    /// Отразить спан нормализованного текста в спан исходного ([`ByteSpan`]
    /// guard-types с перепроверкой UTF-8-границ).
    ///
    /// `None` — спан вне карты, перевёрнутые границы, либо границы не char-границы
    /// оригинала (fail-closed: [`ByteSpan::new`] не пропускает).
    #[must_use]
    pub fn map_span_to_original(
        &self,
        original: &str,
        span_norm: Range<usize>,
    ) -> Option<ByteSpan> {
        let (start, end) = self.map_span(span_norm)?;
        ByteSpan::new(original, start, end).ok()
    }

    /// То же, что [`OffsetMap::map_span_to_original`], но парой байтовых границ
    /// (для тестов, где `ByteSpan` неудобен).
    #[must_use]
    pub fn map_span(&self, span_norm: Range<usize>) -> Option<(usize, usize)> {
        let start = self.map_to_original(span_norm.start)?;
        let end = self.map_to_original(span_norm.end)?;
        (start <= end).then_some((start, end))
    }

    /// Оригинальный текст, из которого собран спан нормализованного текста
    /// (round-trip, инвариант 3). Включает съеденные разделители/марки внутри
    /// фрагмента — это «что подсвечивать» в UI и «что маскировать» в прокси.
    #[must_use]
    pub fn original_for<'o>(&self, original: &'o str, span_norm: Range<usize>) -> Option<&'o str> {
        let (start, end) = self.map_span(span_norm)?;
        original.get(start..end)
    }
}

/// Правила каскада 0, которые здесь СОЗНАТЕЛЬНО не реализованы (хвосты NFKC;
/// точный перечень — требование атома step3a):
///
/// 1. fullwidth/пропорциональные **пунктуация и символы** (`U+FF01…U+FF0F`,
///    `U+FF1A…U+FF20`, `U+FF3B…U+FF40`, `U+FF5B…U+FF65`, `U+FFE0…U+FFE6` —
///    промер: все 94 символа FF01…FF5E имеют `<wide>`-разложение, покрыто
///    только 54 буквенно-цифровых из ТЗ-набора) — на форму чексумм не влияют;
/// 2. лигатуры (`U+FB00…U+FB06`) и буквы с диакритикой в преединичной форме
///    (`U+00C0…U+00FF` → разложение) — латиница вне нашего PII-ядра;
/// 3. математическая алфавитная пропись (`U+1D400…U+1D7FF`), цифры в кружочках
///    (`U+2460…U+24FF`, ⓪ → `0`), римские числители (`U+2160…`) — рерайты, не
///    номерные поля;
/// 4. канонический порядок комбайнинга (reordering классов) и преединичные
///    кирилличные (`U+0401 Ё`, `U+0407 Ї`) — ни туда, ни обратно;
/// 5. `U+00AD` SOFT HYPHEN сознательно НЕ в списке разделителей: между цифрами
///    это перенос слова, а не номер (не додумывать за оператора);
/// 6. NBSP и прочие Zs → обычный пробел (полный NFKC это делает; нам
///    достаточно, что Zs склеивается внутри номерков — вне номерков пробел
///    остаётся пробелом для regex-детекторов);
/// 7. регистронезависимость/casefold — вне ответственности каскада-0.
///
