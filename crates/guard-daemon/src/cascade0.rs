// `passport`/`phone` (model + структурный валидатор), вето = 1.0 на тех же
// `DetectionSource::ChecksumRf`, что у чексумм: proof — формат + контекст,
// сеть его не понижает (SPEC §2).

/// Класс схемы паспорта.
const CLASS_PASSPORT: &str = "passport";

/// Класс схемы телефона.
const CLASS_PHONE: &str = "phone";

/// Класс схемы ИНН (сторона коллизии #200, имя из `schema.default.json`).
const CLASS_INN: &str = "inn";

/// UTF-8-граница символа: байт не является continuation-байтом (`10xxxxxx`).
/// Бюджет контекста отсечён «примерно по символам», срез обязан встать на
/// границу, иначе `from_utf8`/поиск подстроки разрезат кириллицу.
fn norm_char_boundary(bytes: &[u8], i: usize) -> bool {
    i == 0 || i >= bytes.len() || (bytes[i] & 0xC0) != 0x80
}

/// «Буква/цифра слова» для левой границы ключа: ASCII-буквы, цифры,
/// подчёркивание, любая не-ASCII (кириллица слово продолжает).
fn is_word_byte(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_' || !b.is_ascii()
}

/// Есть ли в левом контексте окна (нормализованные байты, окно ≤
/// [`CONTEXT_BUDGET`] символов) один из ключей на границе слова.
///
/// Левая граница ключа обязана быть не-буквенной («тел.» внутри «апартел.» —
/// не ключ); правый край открыт: за «тел.» стоит «: 7 916 …».
fn has_key_left(bytes: &[u8], start: usize, keys: &[&str]) -> bool {
    let budget = CONTEXT_BUDGET.min(start);
    let mut left = start - budget;
    while left < start && !norm_char_boundary(bytes, left) {
        left += 1;
    }
    let hay = &bytes[left..start];
    keys.iter().any(|k| {
        let kb = k.as_bytes();
        kb.len() <= hay.len()
            && hay.windows(kb.len()).enumerate().any(|(i, w)| {
                // Граница слова слева: `i` — ЛОКАЛЬНЫЙ индекс hay-окна.
                // (#213, первичка row352: `hay[i - 1]` на i=0 при left>0 =
                // subtract-with-overflow panic, 503 internal_panic в проде
                // (debug-профиль — паника, release — wrap; в обоих случаях
                // СЕМАНТИКА ЛОЖНАЯ: «ключ на локальном i=0 = ключ в начале
                // hay, глобальная позиция left+i = не начало строки» —
                // проверка границы пропускалась). Глобальная позиция ключа
                // = left+i, локальный индекс — только для hay; на i=0
                // граница слева = байт bytes[left-1] при left>0, else начало
                // строки.)
                w.eq_ignore_ascii_case(kb)
                    && (i > 0 && !is_word_byte(hay[i - 1])
                        || (i == 0 && (left == 0 || !is_word_byte(bytes[left - 1]))))
            })
    })
}

/// Каркас телефона: перед окном канона стоит `+` (через ≤1 пробел) либо
/// ведущий код страны `7`/`8` + скобка/`+`.
///
/// Формы первички #200: `+7 916 123-45-67` (окно = `+7 …` целиком —
/// нормализатор не склеивает `+` с цифрами, окно начинается со скобки/плюса
/// в наших окнах не бывает: `+` не разделитель и не цифра, поэтому окно
/// стартует с `7` и слева видит `+`), `8 (916) 123-45-67` (окно стартует с
/// `9` после `8 (`), `7 916 123-45-67` (окно = все 11 цифр, канон `7916…`).
fn phone_frame_left(bytes: &[u8], start: usize) -> bool {
    // Пропустить пробел-другой и открывающую скобку перед окном.
    let mut i = start;
    let mut spaces = 0usize;
    while i > 0 && (bytes[i - 1] == b'(' || (bytes[i - 1] == b' ' && spaces < 2)) {
        if bytes[i - 1] == b' ' {
            spaces += 1;
        }
        i -= 1;
    }
    if i == 0 {
        return false;
    }
    match bytes[i - 1] {
        b'+' => true,
        // «8 (916) …», «7 (916) …»: код страны цифрой + скобка — окно
        // стартует с `9` (нум-ран кончается перед скобкой, она не разделитель;
        // `8`/`7` в его канон не входят). `i < start` = мы прошли скобку.
        b'8' | b'7' => i < start,
        _ => false,
    }
}

/// Канон каркасного окна: байты без разделителей и скобок.
fn frame_canonical(input: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(input.len());
    let mut i = 0usize;
    while i < input.len() {
        if matches!(input[i], b'(' | b')') {
            i += 1;
            continue;
        }
        let sep = PHONE_FRAME_SEPS
            .iter()
            .find(|sp| input[i..].starts_with(sp))
            .map_or(0, |sp| sp.len());
        if sep == 0 {
            out.push(input[i]);
            i += 1;
        } else {
            i += sep;
        }
    }
    out
}

/// Каркасные окна телефона: прогоны цифр, разделённые списком
/// [`PHONE_FRAME_SEPS`] (разделители номера + пробел + скобки), с ведущим
/// необязательным `+` (он в окно НЕ входит — канон цифры, спан masking'а
/// начинается с цифры, как у всех окон каскада-0).
///
/// Отдельный сканер нужен ровно для каркаса: [`num_runs`] рвётся на скобке
/// («8 (916) …»), а `+` не цифра и не разделитель. Расширение алфавита
/// разделителей телефона безопасно: канон = те же цифры, рамки валидатора
/// (11 цифр `7|8 9xx`) и word-break изоляции ([`isolated`]) остаются;
/// FP-поверхность = 11-значные «номера» со скобками внутри, закрыты вето
/// каркаса/ключа ([`phone_confirmed`]).
fn phone_frame_windows(bytes: &[u8]) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let n = bytes.len();
    // Точка входа = ЦИФРА: каркас склеивается ВПРАВО от неё (`+`/`(` слева
    // пристыковываются ниже). Вход с `+`/`(` рождал окно с чужой ведущей
    // группой: «8 (916) …» от `(` давал окно `(916) 123-45-67` (10 цифр) —
    // не телефон и не каркас, а «+7…» от `7` = чистый канон.
    let mut i = 0usize;
    while i < n {
        if !bytes[i].is_ascii_digit() {
            i += 1;
            continue;
        }
        // Ведущие `+` и открывающая скобка (≤1 пробела) входят в окно:
        // masking обязан крыть весь формат (`+7 916 …`, скобочная форма
        // первички `8 (916) 123-45-67` собирается из цифрового окна `8` +
        // склейки, окно стартует с `8`; «(916) 123-45-67» = окно со скобки).
        let mut start = i;
        let mut back = i;
        let mut spaces = 0usize;
        while back > 0 {
            let prev = bytes[back - 1];
            if prev == b' ' && spaces == 0 {
                spaces += 1;
                back -= 1;
            } else if prev == b'(' && spaces == 0 {
                // Скобка кода: вплотную к цифре или через один пробел.
                back -= 1;
                spaces = usize::MAX; // после скобки назад не идём
            } else if prev == b'+' && back == i {
                // `+` только вплотную (`+7`).
                back -= 1;
                spaces = usize::MAX;
            } else {
                break;
            }
        }
        // Старт = левый принятый байт: он обязан быть каркасным символом
        // (`+`/`(`) — иначе сдвиг на пробел без каркаса («код 916 …» не
        // стартует с «код »).
        if back < i && matches!(bytes[back], b'+' | b'(') {
            start = back;
        }
        loop {
            while i < n && bytes[i].is_ascii_digit() {
                i += 1;
            }
            let sep = PHONE_FRAME_SEPS
                .iter()
                .find(|sp| bytes[i..].starts_with(sp))
                .copied();
            let Some(sep) = sep else { break };
            let j = i + sep.len();
            if j >= n || !bytes[j].is_ascii_digit() {
                break;
            }
            // Рамка ведущей группы #138 для скобочных форм не воспроизводится:
            // «8 (916) …» = ведущая группа одна цифра, и она — код страны
            // (часть канона), не нумерация: телефонный канон 11 цифр `7|8 9xx`
            // проверяется валидатором целиком, суффиксные каноны отсекает
            // длина (окно всегда от первой цифры каркаса).
            i = j;
        }
        // Окно имеет смысл, только если каркас шире простого нум-рана
        // (иначе дубль окна из digit_runs/num_runs — dedup его снимет).
        out.push((start, i));
        // Сканер приседает на следующую цифру: перекрывающихся каркасов нет
        // (внешний каркас ⊇ внутреннего при вложенных скобках — дедюп).
    }
    out
}

/// Разделители каркасного окна: общий перечень номеров ([`NUMBER_SEPARATORS`]
/// через [`sep_len`]) плюс пробел, скобки и их комбинации «пробел+скобка».
/// Порядок значим: «пробел» длиннее не делает — скобка проверяется первой,
/// сдвоенные пробелы не терпят (двойной пробел рвёт прогон, как у [`num_runs`]).
const PHONE_FRAME_SEPS: &[&[u8]] = &[
    b") ",
    b" (",
    b"(",
    b")",
    b" ",
    b"-",
    "\u{2010}".as_bytes(),
    "\u{2011}".as_bytes(),
    "\u{2012}".as_bytes(),
    "\u{FF0D}".as_bytes(),
];

/// Подтверждён ли телефон: каркас ИЛИ ключевое слово слева (док модуля,
/// правила 2–3).
fn phone_confirmed(bytes: &[u8], start: usize, end: usize, canon: &[u8]) -> bool {
    // Каркас-в-каноне: канон 11 цифр начинается с кода страны 7/8 и ТЕКСТ
    // окна начинается с той же цифры (позиции канона в канонизированном
    // срезе: digit_edge — первый байт-цифра окна, `phone_frame_windows`
    // стартует с цифры, «7…», «8 (916) …» = старт 8 = ведущая канона).
    // Голый 11-цифровой суффикс без канонного ведущего (окно «916…» при
    // каноне с ведущей 8/7 = склейка каркаса слева) без каркаса/ключа
    // молчит: 11 цифр на 9 — чужие форматы (СНИЛС 11-значный, счета).
    // Проверка байта ТЕКСТА, а не канона: span masking'а обязан нести
    // канонный префикс (промер #200: «7 916 123-45-67», «79161234567»,
    // «8 (916) 123-45-67» = leading 8; «91612345670» = молчит).
    let canon_frame = (canon.first() == Some(&b'7') || canon.first() == Some(&b'8'))
        && bytes.get(start) == canon.first();
    canon_frame
        // Внутренний `+` каркаса (окно «7 916 …» из «+7 916 …»): «+» в
        // середине окна — телефонный префикс, не арифметика (пробелы вокруг
        // числа с плюсом внутри = номер, не выражение: «1+2» = 1 и 2, не 12).
        || bytes[..start.min(bytes.len())]
            .iter()
            .rev()
            .take(2)
            .any(|&b| b == b'+')
        || phone_frame_left(bytes, start)
        || has_key_left(bytes, start, PHONE_KEYS)
        || has_key_right(bytes, end, PHONE_KEYS_RIGHT)
}

/// Ключ «ИНН» в контексте окна (доминанта коллизии, правило 4): слева в
/// бюджете ИЛИ справа в бюджете — печатная форма «ИНН 4508455561» ставит
/// ключ ПЕРЕД номером, «4508455561 — ИНН юрлица» после; обе = inn.
fn inn_key_near(bytes: &[u8], start: usize, end: usize) -> bool {
    has_key_left(bytes, start, INN_KEYS) || has_key_right(bytes, end, INN_KEYS)
}

/// Есть ли ключ в правом контексте окна (≤ [`CONTEXT_BUDGET`] символов).
fn has_key_right(bytes: &[u8], end: usize, keys: &[&str]) -> bool {
    let budget = CONTEXT_BUDGET.min(bytes.len() - end);
    let mut right = end + budget;
    while right > end && !norm_char_boundary(bytes, right) {
        right -= 1;
    }
    let hay = &bytes[end..right];
    keys.iter().any(|k| {
        let kb = k.as_bytes();
        kb.len() <= hay.len() && hay.windows(kb.len()).any(|w| w.eq_ignore_ascii_case(kb))
    })
}

/// Вето-контур структурного класса для внешнего среза (кандидат-клей
/// модельных обрывков, #200-A1, `pipeline::glue_model_spans` (приватный слой).
///
/// Общая точка с окном-циклом `scan_structured`: победитель склейки обязан подтвердиться
/// тем же вето (формат канона + каркас/ключ), что и детектор каскада-0, —
/// две реализации одного вето расходятся на первой же правке перечня.
/// Срез = текст кандидата (обрывки модели, склеенные разрывом ≤
/// [`crate::pipeline::GLUE_MAX_GAP`]); контекст ищется в нём же (клей не
/// вскрывает соседние слова — решение строго по куску, который станет спаном).
#[must_use]
pub fn structured_confirms(text: &str, class: &str) -> bool {
    let (norm, _map) = normalize::normalize(text);
    let bytes = norm.as_bytes();
    let canon: Vec<u8> = bytes.iter().copied().filter(u8::is_ascii_digit).collect();
    match class {
        CLASS_PHONE => {
            canon.len() == PHONE_SPEC.max
                && call_validator(PHONE_SPEC.name, &canon) == Some(true)
                && phone_confirmed(bytes, 0, canon.len().min(bytes.len()), &canon)
        }
        CLASS_PASSPORT => {
            canon.len() == PASSPORT_SPEC.max
                && call_validator(PASSPORT_SPEC.name, &canon) == Some(true)
                && has_key_left(bytes, bytes.len(), PASSPORT_KEYS)
                && !has_key_left(bytes, bytes.len(), INN_KEYS)
                && !has_key_right(bytes, 0, INN_KEYS)
        }
        _ => false,
    }
}

/// Каркасные слова паспортной формы (#212 F-1): служебные слова, которые
/// печатаются МЕЖДУ серией и номером и рвут цифровой прогон
/// («серия 4508 номер 455561» — «номер» между группами).
///
/// Список — первичка golden-форм + ревью-векторы #211 (94f8f03c): «серия»,
/// «номер», «№». Регистр складывается кириллическим фолдом
/// ([`cyrillic_eq_ignore_case`]): «СЕРИЯ … НОМЕР» = тот же каркас (промер
/// ревью F-4: кап-регистр ключей живёт). Каркасное слово — НЕ ключ: ключевое
/// вето ([`PASSPORT_KEYS`], закрытый перечень) проверяется на левом краю
/// объединённого окна (первичка #212: «`has_key_left` НА ОКНЕ»; «серия» на
/// левом краю и есть ключ). Слово «номер» ключом не становится (бэйт
/// `c0_passport_key_list_is_closed` жив).
const PASSPORT_FRAME_WORDS: &[&[u8]] = &[
    "серия".as_bytes(),
    "номер".as_bytes(),
    "\u{2116}".as_bytes(), // № U+2116 — печатная форма «серия 4508 № 455561»
];

/// Максимальная длина каркасного слова в байтах (рамка сканера: длинный
/// кириллический токен — проза между числами, не каркас).
const PASSPORT_FRAME_WORD_MAX: usize = 10;

/// Сравнение UTF-8-байтов с игнорированием кириллического регистра:
/// побайтовый ASCII-fold кириллицу НЕ складывает («СЕРИЯ» ≠ «серия»),
/// поэтому складываем посимвольно через code point: 2-байтовый UTF-8
/// кириллицы (D0/D1) декодируется, к заглавной (U+0401, U+0410–U+042F —
/// ровно то, что встречается в словах «СЕРИЯ/НОМЕР») прибавляется 0x50
/// (шаг заглавная → строчная), кодирование обратно. Таблица проверяется
/// юнитом `cyrillic_case_fold_matches_rust_lowercase` (тот же крейт:
/// `crates/guard-daemon/src/cascade0.rs`, `mod tests` — НЕ guard-detectors)
/// против `char::to_lowercase` на всём диапазоне + пары Ё/ё.
fn cyrillic_eq_ignore_case(hay: &[u8], word: &[u8]) -> bool {
    fold_kbd_lower(hay) == fold_kbd_lower(word)
}

/// Копия строки в нижнем регистре (ASCII-штатно + кириллица через code
/// point: заглавная U+0401/U+0410–U+042F → +0x50 = re-encode UTF-8).
fn fold_kbd_lower(s: &[u8]) -> Vec<u8> {
    // Побайтовый фолд кириллицы А..Я → а..я + Ё→ё. Таблица (первичка:
    // UTF-8-коды U+0410..U+044F; зуб `cyrillic_case_fold_matches_rust_
    // lowercase` сверяет с `char::to_lowercase` на всём диапазоне + Ё/ё):
    //   А..Й = D0 90..9F → а..й = D0 B0..BF  (второй байт +0x20)
    //   К..Я = D0 A0..AF → к..я = D1 80..8F  (ведущий D0→D1, второй −0x20)
    //   Ё    = D0 81 → ё = D1 91             (пара, вне регулярной сетки)
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while i < s.len() {
        if i + 1 < s.len() && s[i] == 0xD0 {
            let b = s[i + 1];
            if b == 0x81 {
                out.extend_from_slice(&[0xD1, 0x91]);
                i += 2;
                continue;
            }
            if (0x90..=0x9F).contains(&b) {
                out.push(0xD0);
                out.push(b + 0x20);
                i += 2;
                continue;
            }
            if (0xA0..=0xAF).contains(&b) {
                out.push(0xD1);
                out.push(b - 0x20);
                i += 2;
                continue;
            }
        }
        out.push(s[i].to_ascii_lowercase());
        i += 1;
    }
    out
}

fn fold_kbd_upper(s: &[u8]) -> Vec<u8> {
    // Зеркало [`fold_kbd_lower`]: а..й = D0 B0..BF → А..Й (второй −0x20),
    // к..я = D1 80..8F → К..Я (ведущий D1→D0, второй +0x20), ё = D1 91 →
    // Ё = D0 81.
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while i < s.len() {
        if i + 1 < s.len() && s[i] == 0xD0 {
            let b = s[i + 1];
            if (0xB0..=0xBF).contains(&b) {
                out.push(0xD0);
                out.push(b - 0x20);
                i += 2;
                continue;
            }
        }
        if i + 1 < s.len() && s[i] == 0xD1 {
            let b = s[i + 1];
            if b == 0x91 {
                out.extend_from_slice(&[0xD0, 0x81]);
                i += 2;
                continue;
            }
            if (0x80..=0x8F).contains(&b) {
                out.push(0xD0);
                out.push(b + 0x20);
                i += 2;
                continue;
            }
            // (полнота: 0x90..0x9F = ѐ..џ вне русской сетки — не трогается)
        }
        out.push(s[i].to_ascii_uppercase());
        i += 1;
    }
    out
}

/// Ключевое слово формы (любая форма [`PASSPORT_KEYS`] в верхнем регистре,
/// word-break, кириллица складывается [`fold_kbd_upper`]) стоит ПЕРЕД
/// позицией, через разрыв ≤ 3 байт («паспорт 4508 …», «Паспорт: серия 4508
/// …», «Серия 4508, 455561»). Ключевое вето проверяет ключ по полному
/// бюджету [`CONTEXT_BUDGET`]; здесь — каркасность F-1 (форма «ключ 4508
/// ключ 455561», первичка issue) и легитимация голых разрывов моста.
fn passport_key_before(bytes: &[u8], start: usize) -> bool {
    for k in PASSPORT_KEYS {
        let kb = fold_kbd_upper(k.as_bytes());
        for gap in 1..=3usize {
            if start < kb.len() + gap {
                continue;
            }
            let p = start - gap - kb.len();
            let between = &bytes[p + kb.len()..start];
            if fold_kbd_upper(&bytes[p..p + kb.len()]) != kb {
                continue;
            }
            if p > 0 && is_word_byte(bytes[p - 1]) {
                continue;
            }
            if between.iter().all(|&b| {
                b == b' '
                    || b == b','
                    || b == b';'
                    || b == b':'
                    || b == b'|'
                    || b == b'\n'
                    || b == b'\t'
            }) {
                return true;
            }
        }
    }
    false
}

/// Есть ли слово `word` в срезе на границе слова (кириллический регистр через
/// [`cyrillic_eq_ignore_case`], word-break как у [`has_key_left`]).
fn has_word_in(hay: &[u8], word: &str) -> bool {
    let wb = word.as_bytes();
    wb.len() <= hay.len()
        && hay.windows(wb.len()).enumerate().any(|(i, w)| {
            cyrillic_eq_ignore_case(w, wb)
                && (i == 0 || !is_word_byte(hay[i - 1]))
                && (i + wb.len() == hay.len() || !is_word_byte(hay[i + wb.len()]))
        })
}

/// Каркасное слово ровно на позиции `i` (слово из [`PASSPORT_FRAME_WORDS`]
/// на word-break-границе): позиция за словом, если оно там стоит.
fn passport_frame_word(bytes: &[u8], i: usize) -> Option<usize> {
    for w in PASSPORT_FRAME_WORDS {
        if w.len() > PASSPORT_FRAME_WORD_MAX {
            continue;
        }
        if bytes.len() < i + w.len() {
            continue;
        }
        // Кандидат побайтно (word len = exact byte length, список кириллицы
        // фиксированной ширины); регистр складывается фолдом списка/текста.
        let text = &bytes[i..i + w.len()];
        if text != *w && fold_kbd_upper(text) != fold_kbd_upper(w) {
            continue;
        }
        // Граница слева — не-буква («номер» внутри «номера» = не каркас).
        if i > 0 && is_word_byte(bytes[i - 1]) {
            continue;
        }
        let right = i + w.len();
        // Граница справа — НЕ буква. Цифра правым краем не отбивается:
        // слитная печатная форма «№455561» (word «№» + цифры) легитимна.
        // Буква = ASCII-буква или ведущий байт кириллицы (0xD0/0xD1), НЕ
        // любой non-ASCII: пробел (0x20), пунктуация и цифры отбивают.
        if right < bytes.len()
            && (bytes[right].is_ascii_alphabetic() || bytes[right] == 0xD0 || bytes[right] == 0xD1)
        {
            continue;
        }
        return Some(right);
    }
    None
}

/// Каркасные разрывы между группами (помимо служебного слова), которые рвут
/// [`num_runs`] и которые терпит каркас паспорта:
/// - перевод строки / табуляция (нормализатор их сохраняет — промер #212:
///   «Серия 4508\n455561»);
/// - пунктуация перечисления полей «, ; : |» + факультативный одиночный
///   пробел («Серия 4508, 455561», «4508 | 455561»);
/// - открывающая скобка « (» (форма «Серия 4508 (455561)», F-3).
fn passport_break_sep(bytes: &[u8], i: usize) -> usize {
    match bytes.get(i) {
        Some(b'\n' | b'\t') => 1,
        // Пунктуация перечисления полей. Разрыв ведётся от КОНЦА группы:
        // «4508, 455561» = «, »; форма «4508 | 455561» (пробелы с двух
        // сторон) входит через одиночный пробел (`b' '` ниже) + «|» +
        // пробел (мост съедает один пробел после разрыва).
        Some(b',' | b';' | b':' | b'|' | b'(') => {
            // Скобка-разрыв « (» (форма «Серия 4508 (455561)», F-3) живёт
            // в той же ветке: тот же однобайтовый знак + факультативный
            // пробел.
            if bytes.get(i + 1) == Some(&b' ') {
                2
            } else {
                1
            }
        }
        _ => 0,
    }
}

/// Каркасный мост от конца группы `end` к началу следующей группы: позиция
/// первой цифры следующей группы, если разрыв от `end` — каркас паспорта.
///
/// Ключевое слово формы стоит ПЕРЕД ПЕРВОЙ ГРУППОЙ окна: каркас формы
/// «ключ 4508 [ключ] 455561» (первичка issue F-1: «серия 4508 НОМЕР
/// 455561», «Серия 4508, 455561»). Ведущее ключевое слово легитимирует
/// ГОЛЫЕ разрывы (пунктуация/перевод/пробельная ячейка/« и »/скобка):
/// «Серия 4508\n455561» = «Серия» + перевод строки. Без ведущего слова
/// голые разрывы = перечисление полей (FP-контракт g0223 «заполните поле
/// 4508 и приложение 455561»), молчат. Служебное слово в самом разрыве
/// («4508 номер …») легитимно всегда.
///
/// ЯЧЕЙКА (issue #216 (a)+(d)): пробел и табуляция = один и тот же
/// однобайтовый разделитель колонок, в каркасе их терпим ОДНОГО между
/// значащими знаками. Две ячейки подряд = отступ таблицы (перечисление):
/// «4508  455561» (ровно два — легальная печатная форма, первичка #212)
/// и «4508\t\t455561» (таб twice = колонки таблицы) живут по-разному,
/// промер таблицы — юнитами `c0_passport_frame_*`.
fn passport_bridge(bytes: &[u8], end: usize, key_before: bool) -> Option<usize> {
    // Одна пробельная ячейка (пробел ИЛИ таб), не две.
    let cell = |i: usize| matches!(bytes.get(i), Some(b' ' | b'\t'));
    let digit = |i: usize| bytes.get(i).is_some_and(u8::is_ascii_digit);
    let punct = |i: usize| matches!(bytes.get(i), Some(b'|' | b',' | b';' | b':'));
    // Каркасное слово с факультативным колоном (#216 (e)): позиция за словом.
    let word_at = |i: usize| {
        passport_frame_word(bytes, i).map(|we| {
            if bytes.get(we) == Some(&b':') {
                we + 1
            } else {
                we
            }
        })
    };
    // 1) Служебное слово в разрыве: одиночная ячейка («4508 номер …»,
    //    «4508\tномер …» #216 (d)), пунктуация + ячейка («4508, номер …»,
    //    «4508 |\tномер …»), слитные формы «№455561», «номер:455561»;
    //    за словом — одиночная ячейка, пунктуация + ячейка, скобка +
    //    пробел (форма «4508 | номер | 455561»), и цифра.
    let s0 = passport_break_sep(bytes, end);
    let mut bases = Vec::new();
    if cell(end) {
        bases.push(end + 1);
    }
    if s0 > 0 && cell(end + s0) {
        bases.push(end + s0 + 1);
    }
    for base in bases {
        if base >= bytes.len() {
            continue;
        }
        let mut p = base;
        for _ in 0..2 {
            let Some(we) = word_at(p) else { break };
            if digit(we) {
                return Some(we); // слитная форма «№455561», «номер:455561»
            }
            // за словом: одиночная ячейка | пунктуация + ячейка | скобка
            let ps = passport_break_sep(bytes, we);
            let q = if ps > 0 && cell(we + ps) {
                we + ps + 1
            } else if cell(we) && !cell(we + 1) {
                we + 1
            } else if bytes.get(we) == Some(&b'(') && bytes.get(we + 1) == Some(&b' ') {
                we + 2
            } else {
                break;
            };
            if digit(q) {
                return Some(q);
            }
            p = q;
        }
    }
    // 2) Голые каркасные разрывы — только при ведущем слове формы
    //    (legitimized на входе сканера): «4508\n455561», «4508, 455561»,
    //    «4508 | 455561», «4508 (455561)», «4508  455561», «4508\t455561»,
    //    «4508 и 455561». Без ведущего слова голые разрывы = перечисление
    //    полей (FP-контракт g0223), молчат.
    if !key_before {
        return None;
    }
    // Разрыв-знак (`passport_break_sep`: перевод строки, пунктуация, скобка)
    // + одна факультативная ячейка + цифра: «4508\n455561», «4508, 455561»,
    // «4508, 455561», «4508\t| 455561» (#216 (d): таб = ячейка, знак после).
    if s0 > 0 {
        let p = end + s0;
        if digit(p) {
            return Some(p);
        }
        // ОДИН пробел после разрыв-знака = каркас («4508, 455561»,
        // «4508 | 455561»); табуляция после знака = колонка таблицы,
        // молчит (#216 (d): таб каркасен только КАК ЕДИНСТВЕННЫЙ знак).
        if s0 == 1 && bytes.get(p) == Some(&b' ') && digit(p + 1) {
            return Some(p + 1);
        }
    }
    // Ячейка + пунктуация (+ факультативная ячейка): «4508 | 455561» —
    // разделитель с ячейками с двух сторон (ревью-вектор); таб = та же
    // ячейка: «4508\t| 455561» (#216 (d)). За знаком — цифра ИЛИ каркасное
    // слово: «4508 | номер 455561» (#216 (a) — знак симметричен ячейке).
    if cell(end) && punct(end + 1) {
        let mut p = end + 2;
        if cell(p) {
            p += 1;
        }
        if digit(p) {
            return Some(p);
        }
        if let Some(we) = word_at(p)
            && cell(we)
            && !cell(we + 1)
            && digit(we + 1)
        {
            return Some(we + 1);
        }
    }
    // « и » литеральный разделитель (одинарные пробелы с обеих сторон:
    // «4508  и 2015» = перечисление; «4508 и  2015» = третий пробел).
    if bytes.get(end) == Some(&b' ')
        && bytes[end + 1..].starts_with("и ".as_bytes())
        && bytes.get(end + 1 + "и ".len()) != Some(&b' ')
    {
        let p = end + 1 + "и ".len();
        if digit(p) {
            return Some(p);
        }
    }
    // «4508  455561»: ровно ДВА пробела (первичка #212; третий = перечисление).
    if bytes.get(end) == Some(&b' ') && bytes.get(end + 1) == Some(&b' ') && digit(end + 2) {
        return Some(end + 2);
    }
    // Табуляция = каркасный разделитель колонки (#216 (d): первичка golden —
    // табуляции в датасете нет, bait-контракта на молчание не зафиксировано;
    // head вёл таб как разделитель в ветке разрыв-знака). ОДИН таб; второй
    // таб подряд = колонка таблицы («4508\t\t455561»), молчит.
    if bytes.get(end) == Some(&b'\t') && bytes.get(end + 1) != Some(&b'\t') && digit(end + 1) {
        return Some(end + 1);
    }
    None
}

/// Есть ли в гэпе каркасное слово списка (issue #216 (a)+(e)): слово на
/// word-break-границе с факультативным ASCII-колоном справа. Гэп — срез между
/// группами цифр (« номер », « | номер: », «\tномер »); голое вхождение без
/// границ (« телефонномер ») каркасом не считается — тот же word-break, что у
/// [`passport_frame_word`] на полном тексте.
fn gap_has_frame_word(gap: &[u8]) -> bool {
    ["серия", "номер", "\u{2116}"].iter().any(|w| {
        let wb = w.as_bytes();
        gap.windows(wb.len()).enumerate().any(|(i, x)| {
            // Слово + факультативный колон: хвост [i..] отдаём word-break-зубу
            // `has_word_in` (колон = не буква: правая граница слова после
            // него — тот же word-break, что у [`passport_frame_word`]).
            cyrillic_eq_ignore_case(x, wb)
                && (i == 0 || !is_word_byte(gap[i - 1]))
                && has_word_in(&gap[i..], w)
        })
    })
}

/// Каркасные окна паспорта (#212 F-1): группы цифр, склеенные каркасными
/// мостами ([`passport_bridge`]). Скользящее окно по группам:
/// - старт = группа полной ширины ([`MIN_LEADING_GROUP_DIGITS`], leading-рамка
///   #138: «1 4508 номер 455561» = нумерация);
/// - шаг = каркасный мост к следующей группе полной ширины и не длиннее
///   [`MAX_GROUP_DIGITS`] (общие рамки оконного слоя);
/// - окно ≤ [`MAX_WINDOW_GROUPS`] групп, каркас окна ≤ [`CONTEXT_BUDGET`]
///   байт (расстояние-бюджет #51-контура, новых констант нет);
/// - правая рамка F-2 [`passport_tail_break`]: хвост 3..=6 цифр = чужое поле,
///   окно обрывается ДО хвоста (паспорт «находится чисто»);
/// - спан сужается до цифр окна (F-3, [`passport_span_trim`]).
///
/// Окна < 2 групп не строятся (10-канона без второй группы не бывает).
fn passport_frame_windows(bytes: &[u8]) -> Vec<(usize, usize)> {
    let n = bytes.len();
    let mut out = Vec::new();
    let mut i = 0usize;
    while i < n {
        if !bytes[i].is_ascii_digit() {
            i += 1;
            continue;
        }
        let gstart = i;
        while i < n && bytes[i].is_ascii_digit() {
            i += 1;
        }
        let gend = i;
        if gend - gstart < MIN_LEADING_GROUP_DIGITS {
            continue;
        }
        let start = gstart;
        let mut end = gend;
        let mut groups = 1usize;
        loop {
            if groups >= MAX_WINDOW_GROUPS {
                break;
            }
            // Ведущее ключевое слово формы считается от ПЕРВОЙ группы окна
            // («серия 4508 …»): оно легитимирует голые разрывы на всём окне.
            let key_before = passport_key_before(bytes, start);
            // Мост ПЕРВЫМ порядком: каркасное слово в гэпе = форма паспорта,
            // хвост за цифрами («… номер 455561 2015») не отменяет мост к
            // номеру; F-2 (рамка хвоста) отсечёт окно ПОСЛЕ склейки групп.
            let Some(j) = passport_bridge(bytes, end, key_before) else {
                break;
            };
            if passport_tail_break(bytes, end).is_some() {
                break;
            }
            let mut k = j;
            while k < n && bytes[k].is_ascii_digit() {
                k += 1;
            }
            let glen = k - j;
            if !(MIN_LEADING_GROUP_DIGITS..=MAX_GROUP_DIGITS).contains(&glen) {
                break;
            }
            if k - start > 10 * groups + CONTEXT_BUDGET {
                break; // каркас за расстоянием-бюджетом #51-контура
            }
            end = k;
            groups += 1;
            i = k;
        }
        // Окно значимо при каркасной форме: слово в гэпе, союз « и »,
        // скобка-разрыв (F-3) или ведущее ключевое слово формы
        // (legitimized-мосты); голые перечислительные разрывы без
        // ведущего слова мостом не склеиваются (FP-контракт g0223).
        if groups >= 2 && passport_frame_shape_ok(bytes, start, end) {
            let worded = gaps_of(bytes, start, end).into_iter().any(|gap| {
                gap == " и ".as_bytes()
                    || gap.contains(&b'(')
                    || gap.contains(&b')')
                    || gap_has_frame_word(gap)
            });
            if (worded || passport_key_before(bytes, start))
                && let Some(span_end) = passport_span_trim(bytes, start, end)
            {
                out.push((start, span_end));
            }
        }
    }
    out
}

/// Правая рамка паспорта (#212 F-2): хвост 3..=6 цифр, прижатый к канону
/// ASCII-пробелом/дефисом, окно ОБРЫВАЕТ; хвост ≥ 7 цифр — продолжение
/// номера (окно отшивается общей правой границей, симметрия с
/// `right_sep_continues` каркаса).
///
/// Первичка ревью-вектора (94f8f03c §F-2): «паспорт 4508 455561 123» на базе
/// = no spans, FN-класс симметричен левой рамке #138 (цена anti-FP).
/// РЕШЕНИЕ ПЕРВИЧКОЙ ревью-описания и golden-бейтов: цель ревью — «паспорт
/// НЕ находится при right-рамка-дата ИЛИ находится чисто». 4+6-форма =
/// СЕРИЯ (4) + НОМЕР (6); после номера печатаются ДАТА («… 455561
/// 15.04.2015» — точка рвёт прогон вето #131, окно остаётся чистым:
/// первичка g0205 «Паспорт 4508 455561 выдан 15.04.2015» покрыта), год
/// («… 2015» = 4 цифры), чужое поле произвольной кратности; слитый канон
/// 10+k цифр = НЕ паспортная форма (канон-суффикс, то же зло, что закрыто
/// рамкой #138 слева). Хвост 1–2 цифры (12/123-хвосты, «… 12») остаются в
/// каноне и отшиваются длиной валидатора (11–12 цифр — не паспорт), как на
/// базе: форма «12/123» первичкой ревью НЕ заявлена ожидаемой (FN «123»
/// закрывается, «12/123» остаётся вFP-safe молчании — промер таблицы PR).
/// Отдельные валидаторы даты/года в список НЕ вынесены: оба решения живут
/// одним правилом, второй реализации того же решения не заводим.
fn passport_tail_break(bytes: &[u8], end: usize) -> Option<usize> {
    if !matches!(bytes.get(end), Some(b' ' | b'-')) {
        return None;
    }
    // Слово каркаса в гэпе — не хвост («4508 номер 455561»: хвост за 4508 =
    // «номер», не цифры): F-2 режет ГОЛЫЕ числовые хвосты, слово узаконено
    // мостом.
    if bytes[end + 1..].starts_with("и ".as_bytes()) {
        return None;
    }
    let mut j = end + 1;
    let mut len = 0usize;
    while bytes.get(j).is_some_and(u8::is_ascii_digit) {
        j += 1;
        len += 1;
    }
    if bytes.get(j).is_some_and(u8::is_ascii_digit) {
        return None;
    }
    if (3..=6).contains(&len) {
        return Some(j);
    }
    None
}

/// Сужение спана каркасного окна (F-3, ревью #211: «Серия 4508 (455561)»
/// давала спан с внутренней открывающей скобкой). Спан = от ПЕРВОЙ цифры до
/// ПОСЛЕДНЕЙ цифры окна (каркас outside — как `+` вне спана телефона);
/// каркасные скобки внутри спана ВЫРЕЗАЮТСЯ (маскировать надо `ПДн`, не
/// типографику): «4508 (455561)» → «4508 455561». Канон спана обязан
/// равняться канону окна (цифры те же; между группами остаются пробелы) —
/// иначе fail-closed: окно отшивается.
fn passport_span_trim(bytes: &[u8], start: usize, end: usize) -> Option<usize> {
    // Спан = от ПЕРВОЙ цифры до ПОСЛЕДНЕЙ цифры окна (F-3: каркасная
    // скобка на КРАЮ окна из спана выпадает: «Серия (4508) …» → спан
    // «4508 …»). Внутренняя скобка («4508 (455561)») между цифрами из
    // непрерывного спана выпасть НЕ может (маскируется вместе с канон-
    // разделителем — тот же смысл, что «, »/«\n» внутри спанов F-1:
    // канон извлекается по цифрам, спан = непрерывный фрагмент текста).
    let inner = &bytes[start..end];
    let last = inner.iter().rposition(u8::is_ascii_digit)?;
    let _ = inner.iter().position(u8::is_ascii_digit)?;
    let out_end = start + last + 1;
    Some(out_end)
}

/// Канон окна без каркасных байт: только цифры среза (каркасные слова,
/// пунктуация и переводы строк в канон не входят — тот же смысл, что у
/// `Run::canonical`: валидатор видит группы, склеенные в форму).
fn canon_all_digits(bytes: &[u8], start: usize, end: usize) -> Vec<u8> {
    bytes[start..end]
        .iter()
        .copied()
        .filter(u8::is_ascii_digit)
        .collect()
}

/// Вето паспорта для каркасного окна F-1 ([`passport_frame_windows`]):
/// - word-break на цифровых краях окна (прижатие к букве/цифре = не форма);
/// - канон = 10 цифр ([`PASSPORT_SPEC`]), zero-canon #158 в
///   [`call_validator`];
/// - каркас окна доказан: каждый гэп между группами — ЛИБО слово из
///   [`PASSPORT_FRAME_WORDS`], ЛИБО разрыв без букв (список
///   [`passport_break_sep`], « и », два пробела); гэп с чужим словом
///   («4508 телефон 455561») окно отшивает (список закрытый);
/// - СМЫСЛ F-1 — каркасное слово в окне или перед ним (первичка #212:
///   «ключ 4508 ключ 455561»; формы без слова — «4508, 455561» с «Серия»
///   слева — ведут себя как «Серия 4508 455561»: ключевое вето их берёт);
/// - ключ [`PASSPORT_KEYS`] на левом краю ОБЪЕДИНЁННОГО окна
///   ([`has_key_left`], бюджет [`CONTEXT_BUDGET`], word-break — первичка
///   #212 bug-формулировки: «4508 серия 455561» с пустым левым контекстом
///   молчит, FP-контракт g0223 «поле 4508 и приложение 455561» живёт);
/// - «ИНН»-доминанта (правило 4) — общая.
fn passport_window_verdict(
    bytes: &[u8],
    start: usize,
    end: usize,
    canon: &[u8],
) -> Option<&'static str> {
    if !isolated(bytes, start, end) {
        return None;
    }
    if canon.len() != PASSPORT_SPEC.max {
        return None;
    }
    if call_validator(PASSPORT_SPEC.name, canon) != Some(true) {
        return None;
    }
    if !passport_frame_shape_ok(bytes, start, end) {
        return None;
    }
    if !has_key_left(bytes, start, PASSPORT_KEYS) {
        return None;
    }
    if inn_key_near(bytes, start, end) {
        return None;
    }
    Some(CLASS_PASSPORT)
}

/// Каркасность окна по гэпам: каждый гэп между группами цифр — слово списка
/// (word-break) или разрыв без букв. Гэп с чужим словом = не каркас.
fn passport_frame_shape_ok(bytes: &[u8], start: usize, end: usize) -> bool {
    // Гэп окна легален, если это: каркасное слово списка (« серия »,
    // « номер », « № »), союз « и » (печатная форма), либо разрыв БЕЗ букв
    // (пробелы, пунктуация, перевод строки, скобки — всё, что построил
    // мост). Гэп с чужим словом (« телефон », « счёт ») окно отшивает:
    // список каркасных слов закрытый.
    let letter = |b: u8| b.is_ascii_alphabetic() || b == 0xD0 || b == 0xD1;
    gaps_of(bytes, start, end).into_iter().all(|gap| {
        !gap.iter().any(|&b| letter(b)) || gap == " и ".as_bytes() || gap_has_frame_word(gap)
    })
}

fn gaps_of(bytes: &[u8], start: usize, end: usize) -> Vec<&[u8]> {
    let inner = &bytes[start..end];
    let n = inner.len();
    // Собираем сразу (окна короткие): гэп = нецифровой кусок, за которым
    // (внутри среза) идёт цифра, и перед которым шла цифра.
    let mut gaps: Vec<&[u8]> = Vec::new();
    let mut i = 0;
    while i < n && !inner[i].is_ascii_digit() {
        i += 1;
    }
    while i < n {
        while i < n && inner[i].is_ascii_digit() {
            i += 1;
        }
        let g = i;
        while i < n && !inner[i].is_ascii_digit() {
            i += 1;
        }
        if i < n && i > g {
            gaps.push(&inner[g..i]);
        }
    }
    gaps
}

/// Есть ли в срезе каркасная не-цифра (не пробел/дефис, не цифра): кириллица
/// слова, пунктуация, перевод строки, скобка. Голый пробельный/дефисный
/// прогон = окно общего контура ([`num_runs`]), каркасный сканер такие окна
/// не строит (и не должен: дубль FP-поверхности).
fn passport_frame_has_break(bytes: &[u8], start: usize, end: usize) -> bool {
    bytes[start..end]
        .iter()
        .any(|&b| !b.is_ascii_digit() && b != b' ' && b != b'-')
}

/// Каркасный проход паспорта (#212 F-1/F-2): окна [`passport_frame_windows`]
/// + правая рамка F-2 для окон общего контура.
fn scan_passport_frames(bytes: &[u8], passports: &mut Vec<(usize, usize)>) {
    for (start, end) in passport_frame_windows(bytes) {
        let canon = canon_all_digits(bytes, start, end);
        if passport_window_verdict(bytes, start, end, &canon).is_some() {
            passports.push((start, end));
        }
    }
    // F-2 для окон общего контура: num-run «4508 455561 2015» (канон 13
    // цифр) отшит общей правой границей; паспортная форма под ним
    // («ключ 4508 455561 2015») существует, и хвост 3..=6 цифр = чужое
    // поле: окно обрезается рамкой [`passport_tail_break`] и подтверждается
    // полным вето [`classify_structured_window`] (формат, ключ, leading,
    // zero-canon, inn-доминанта — ничего не ослаблено).
    for run in num_runs(bytes) {
        let first = run
            .groups
            .iter()
            .position(|g| g.end - g.start >= MIN_LEADING_GROUP_DIGITS)
            .unwrap_or(0);
        let start = run.groups[first].start;
        let Some(end) = passport_tail_break(bytes, run.groups[run.groups.len() - 1].end) else {
            continue;
        };
        // Окно с каркасной не-цифрой между группами принадлежит каркасному
        // сканеру выше; здесь только голые пробельные прогоны.
        if passport_frame_has_break(bytes, start, end) {
            continue;
        }
        if classify_structured_window(bytes, start, end, true, false) == Some(CLASS_PASSPORT) {
            passports.push((start, end));
        }
    }
}

/// Кандидатные окна структурного слоя: цифровые прогоны + нум-раны с рамкой
/// #138 + каркасные окна телефона; сортировка/дедуп (тот же оконный контур,
/// что у `validated_windows`).
fn structured_windows(bytes: &[u8]) -> Vec<(usize, usize)> {
    let mut windows: Vec<(usize, usize)> = digit_runs(bytes);
    for run in num_runs(bytes) {
        let first = run
            .groups
            .iter()
            .position(|g| g.end - g.start >= MIN_LEADING_GROUP_DIGITS)
            .unwrap_or(0);
        // Рамка ведущей группы #138 (док модуля, правило 5): прогон с
        // ведущей цифрой-нумерацией окно не даёт (канон-суффикс «1 234 567 …»).
        if run.groups[0].end - run.groups[0].start >= MIN_LEADING_GROUP_DIGITS
            || run.groups.len() == 1
        {
            windows.push((
                run.groups[first].start,
                run.groups[run.groups.len() - 1].end,
            ));
        }
    }
    // Каркасные окна телефона (#200-A2): общий нум-ран рвётся на скобке
    // («8 (916) 123-45-67» = «8» | «916) 123-45-67») и не терпит `+`/`(`/`)`
    // внутри номера: окна собирает отдельный каркасный сканер.
    windows.extend(phone_frame_windows(bytes));
    // Каркасные окна паспорта (#212 F-1): тот же принцип — общий нум-ран
    // рвётся на служебном слове («серия 4508 номер 455561»), сдвоенном
    // пробеле, переводе строки и пунктуации: окна собирает каркасный сканер
    // паспорта (ведёт вето `passport_window_verdict`).
    windows.sort_unstable();
    windows.dedup();
    windows
}

/// Из окон с одинаковым КАНОНОМ оставляем самое широкое (start↑, end↓):
/// вложенные дубляжи одного номера = одна находка, спан masking'а = полный
/// формат (как `drop_contained` для чексумм).
fn collapse_same_canon(wins: &mut Vec<(usize, usize)>, bytes: &[u8]) {
    wins.sort_unstable_by_key(|&(s, e)| (s, std::cmp::Reverse(e)));
    let mut i = 0usize;
    while i < wins.len() {
        let mut j = i + 1;
        while j < wins.len()
            && frame_canonical(&bytes[wins[j].0..wins[j].1])
                == frame_canonical(&bytes[wins[i].0..wins[i].1])
        {
            j += 1;
        }
        wins.drain(i + 1..j);
        i += 1;
    }
}

/// Структурный проход #200-A2: паспорт/телефон + взаимное вето коллизий.
///
/// Окна — те же [`num_runs`] + [`digit_runs`] с общими рамками #138 (док
/// модуля, правило 5); канон — [`strip_separators`], валидатор —
/// [`call_validator`] (zero-canon #158 applies: «0000 000000» паспортом не
/// станет).
/// Что структурный слой решил про окно: класс подтверждения (None = окно
/// не подтверждено ни одним вето).
fn classify_structured_window(
    bytes: &[u8],
    start: usize,
    end: usize,
    want_passport: bool,
    want_phone: bool,
) -> Option<&'static str> {
    // Изоляция: окно каркаса может начинаться с `+` (не-буквенно-цифровой
    // байт, `isolated` для него истинна и на внутреннем `+`, поэтому
    // проверка идёт по цифровому краю окна — первому байту-цифре).
    // Рамка ведущей группы #138 — общая с оконным циклом: каркасное окно
    // не имеет права начинаться с цифры-нумерации («1.4508 455561»,
    // «1 234 567 890»). Первый байт канона — первая цифра окна.
    let digit_edge = if bytes[start].is_ascii_digit() {
        start
    } else {
        start + 1
    };
    // Правая рамка паспорта #212 F-2 (окна ОБЩЕГО контура): хвост 3..=6 цифр
    // = чужое поле, паспортное окно обрывается до него (окно = 10-канон
    // серия+номер, «находится чисто»). Для окон каркасного паспорта F-1 рамка
    // применена на сканере; здесь симметрия для «паспорт 4508 455561 123»
    // (num-run-окно 4508..123 канон 13 цифр → ниже канон не 10 → паспортного
    // хита нет; обрезанное окно даёт его). Телефонная ветка НЕ трогается:
    // рамка паспортная, «+7 916 123-45-67 2015» = телефон + год (промер
    // ревью: телефон живёт, хвост не его).
    // Правый край окна обязан сидеть на ГРАНИЦЕ слова: за окном нет
    // цифры, нет «пробел/дефис + цифра» (правая граница общего
    // num-runs-контура: «1 234 567 890 12» не склеивается каркасом в
    // 11 цифр из нумерации) и нет скобки/плюса — продолжение каркаса
    // («8 (916) 123-45-67» от цифры `8`: сепс « (» склеивает сам).
    let right_sep_continues = sep_len_number(bytes, end) > 0
        && bytes
            .get(end + sep_len_number(bytes, end))
            .is_some_and(u8::is_ascii_digit);
    // Правая граница окна = конец каркасного прогона (сканер сам доводит
    // `end` до первой позиции, где склейка невозможна), поэтому продолжение
    // справа проверяем только общими сепсами и скобкой/плюсом: каркасные
    // сепсы не дают «окну-половинке» выживать («8 (916)» vs «123-45-67»).
    if bytes.get(end).is_some_and(u8::is_ascii_digit)
        || bytes[end..].starts_with(b"(")
        || bytes.get(end) == Some(&b'+')
        || right_sep_continues
    {
        return None;
    }
    if !isolated(bytes, digit_edge, end) {
        return None;
    }
    // Канон каркасного окна чистится по тому же перечню, что склеивал
    // (`PHONE_FRAME_SEPS` ⊇ NUMBER_SEPARATORS), плюс скобки: «8 (916)
    // 123-45-67» = канон 89161234567. Для окон без каркасных символов
    // результат совпадает со `strip_separators`.
    let canon = frame_canonical(&bytes[digit_edge..end]);
    // Ключи ищутся по границе ЦИФРЫ (`digit_edge`): каркасные байты
    // (`+`, скобки) не являются word-байтами, и ключ «тел.» перед
    // «+7…» стоит на дистанции в 1 байт от канона.
    // Телефон (правило 2): канон 11 цифр `7|8 9xx` + каркас/ключ.
    if want_phone
        && canon.len() == PHONE_SPEC.max
        && call_validator(PHONE_SPEC.name, &canon) == Some(true)
        && phone_confirmed(bytes, digit_edge, end, &canon)
    {
        return Some(CLASS_PHONE);
    }
    // Коллизия 10-значного суффикса (первичка #200: «телефон
    // 916 123-45-67» = валидный ИНН-10 по формуле, суффикс мобильного):
    // 10 цифр на 9xx + телефонный каркас/ключ слева = phone-доминанта
    // (спан суффикса); inn-хит этого окна гасится правилом 3 ниже.
    if want_phone
        && canon.len() == PASSPORT_SPEC.max
        && canon.first() == Some(&b'9')
        && (phone_frame_left(bytes, digit_edge)
            || has_key_left(bytes, digit_edge, PHONE_KEYS)
            || has_key_right(bytes, end, PHONE_KEYS_RIGHT))
        && !inn_key_near(bytes, digit_edge, end)
    {
        return Some(CLASS_PHONE);
    }
    // Паспорт (правило 1): канон ровно 10 цифр 4+6 + ключ, без «ИНН»-ключа.
    // Ведущая рамка #138: каркасное окно с ведущей группой в 1 цифру
    // паспортом не становится («1 4508 4555 61» = нумерация; телефон
    // своей формой 11-`7|8 9xx` выше, телефонная валидация её не трогает).
    let lead_len = digit_run_len_after(bytes, digit_edge);
    if want_passport
        && lead_len >= MIN_LEADING_GROUP_DIGITS
        && canon.len() == PASSPORT_SPEC.max
        && call_validator(PASSPORT_SPEC.name, &canon) == Some(true)
        && has_key_left(bytes, digit_edge, PASSPORT_KEYS)
        && !inn_key_near(bytes, digit_edge, end)
    {
        return Some(CLASS_PASSPORT);
    }
    None
}

fn scan_structured(
    text: &str,
    bytes: &[u8],
    map: &normalize::OffsetMap,
    wanted: &[(&'static str, ClassId)],
    hits: &mut Vec<Hit>,
) {
    let want_passport = wanted
        .iter()
        .any(|(v, c)| *v == PASSPORT_SPEC.name && c.as_str() == CLASS_PASSPORT);
    let want_phone = wanted
        .iter()
        .any(|(v, c)| *v == PHONE_SPEC.name && c.as_str() == CLASS_PHONE);
    if !(want_passport || want_phone) {
        return;
    }

    let windows = structured_windows(bytes);

    let mut phones: Vec<(usize, usize)> = Vec::new();
    let mut passports: Vec<(usize, usize)> = Vec::new();

    for (start, end) in windows {
        match classify_structured_window(bytes, start, end, want_passport, want_phone) {
            Some(CLASS_PHONE) => phones.push((start, end)),
            Some(CLASS_PASSPORT) => passports.push((start, end)),
            _ => {}
        }
    }
    // Каркас окна паспорта (#212 F-1/F-2): собственная ветка (слово в окне
    // ломает общий word-break/канон), окно получает вето по цифровому канону.
    if want_passport {
        scan_passport_frames(bytes, &mut passports);
    }
    // Вложенные окна (каркас ⊇ нум-ран ⊇ подокно) дают дубли одного номера:
    // из окон класса с одинаковым КАНОНОМ оставляем самое широкое (спан
    // masking'а = полный формат, как `drop_contained` для чексумм).
    collapse_same_canon(&mut phones, bytes);
    collapse_same_canon(&mut passports, bytes);

    // Правило 5: паспортное окно внутри подтверждённого телефона гасится
    // (суффикс мобильного = 10 цифр паспортного формата).
    passports.retain(|p| !phones.iter().any(|ph| ph.0 <= p.0 && p.1 <= ph.1));

    // Правило 3: inn-хит, лежащий строго внутри телефонного окна (суффикс
    // 10 цифр подтверждённого `7|8 916…`), гасится — телефонная доминанта
    // (промер первички: `7 916 123-45-67` = inn 1.0 на суффиксе). Сравнение в
    // координатах оригинала: окно телефона мапится через ту же карту, что и
    // спаны.
    if !phones.is_empty() {
        let phone_orig: Vec<(usize, usize)> = phones
            .iter()
            .filter_map(|&(s, e)| map.map_span(s..e))
            .collect();
        hits.retain(|h| {
            !(h.class.as_str() == CLASS_INN
                && phone_orig.iter().any(|(ps, pe)| {
                    // Inn-окно вложено в телефонное (10 ⊂ 11: суффикс,
                    // префикс, середина — всё чтения одного телефона).
                    h.span.start >= *ps && h.span.end <= *pe
                }))
        });
    }

    for (start, end) in passports {
        if let Some(span) = map.map_span_to_original(text, start..end) {
            hits.push(Hit {
                span,
                class: ClassId::new(CLASS_PASSPORT),
                validator: PASSPORT_SPEC.name,
                source: PASSPORT_SPEC.source,
            });
        }
    }
    for (start, end) in phones {
        if let Some(span) = map.map_span_to_original(text, start..end) {
            hits.push(Hit {
                span,
                class: ClassId::new(CLASS_PHONE),
                validator: PHONE_SPEC.name,
                source: PHONE_SPEC.source,
            });
        }
    }
}

/// Минимальная полезная нагрузка декода, байт.
///
/// 11 — это ИНН-10 с одной перемычкой (`778524 0858`): короче нечего проверять
/// чексумме, а каждая лишняя проверка короткого канона — это FP-поверхность.
/// Побочный эффект порога известен и принят: blob, в котором ровно 10 байт
/// «2482014338» без обрамления, не проверяется (тест
/// `base64_payload_floor_is_the_documented_tradeoff`).
const B64_MIN_PAYLOAD_BYTES: usize = 11;

/// Минимальная длина кандидата, байт: 16 — ближайшее кратное 4, чей декод не
/// короче [`B64_MIN_PAYLOAD_BYTES`]. Дешёвый префильтр: отсекает кандидатов до
/// того, как мы вообще посмотрим на алфавит.
const B64_MIN_TOKEN_BYTES: usize = 16;

/// Символы обоих алфавитов base64 плюс паддинг: standard `A-Za-z0-9+/`,
/// url-safe `A-Za-z0-9-_`, `=`.
const fn is_b64_symbol(b: u8) -> bool {
    b.is_ascii_alphanumeric() || matches!(b, b'+' | b'/' | b'-' | b'_' | b'=')
}

/// Кандидаты base64: токены алфавита, ограниченные пробелом с обеих сторон.
///
/// Граница — пробел (в нормализованном тексте все Zs уже сведены к U+0020), а
/// не «любой не-алфавитный символ». Это и есть ответ на «почему JWT не
/// декодируется»: `a.b.c` — один токеном-не-токен, точки разрывают алфавит, но
/// части не стоят на пробельной границе, а прижатая к букве base64-цепочка
/// (`sha256=…`, `data:…;base64,AAAA…`, `[[F0#base64url]]` нашего же vault) —
/// это поле формата, а не вставка пользователя. Последнее важно не только для
/// FP: разворачивать собственный маркер обратимости означало бы маскировать
/// токен, который прокси сам вставляет в тело (#60).
fn b64_tokens(bytes: &[u8]) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let n = bytes.len();
    let mut i = 0usize;
    while i < n {
        if !is_b64_symbol(bytes[i]) {
            i += 1;
            continue;
        }
        let start = i;
        while i < n && is_b64_symbol(bytes[i]) {
            i += 1;
        }
        let end = i;
        let left_ws = start == 0 || bytes[start - 1].is_ascii_whitespace();
        let right_ws = end == n || bytes[end].is_ascii_whitespace();
        if !(left_ws && right_ws) {
            continue;
        }
        if b64_shape_ok(&bytes[start..end]) {
            out.push((start, end));
        }
    }
    out
}

/// Форма кандидата: длина кратна 4 и не короче [`B64_MIN_TOKEN_BYTES`],
/// паддинг только хвостом (≤ 2), алфавит в токене не смешан.
///
/// Каноничность паддинга и «мусор в хвосте» доверены декодеру:
/// `general_purpose::STANDARD`/`URL_SAFE` требуют каноничный паддинг
/// (`DecodePaddingMode::RequireCanonical`) и не терпят лишних битов, так что
/// здесь только то, что декодер по своим правилам не отвергает.
fn b64_shape_ok(tok: &[u8]) -> bool {
    if tok.len() < B64_MIN_TOKEN_BYTES || !tok.len().is_multiple_of(4) {
        return false;
    }
    let mut pads = 0usize;
    let mut standard = false;
    let mut url_safe = false;
    let mut seen_pad = false;
    for &b in tok {
        match b {
            b'=' => {
                pads += 1;
                seen_pad = true;
            }
            b'+' | b'/' => {
                if seen_pad {
                    return false;
                }
                standard = true;
            }
            b'-' | b'_' => {
                if seen_pad {
                    return false;
                }
                url_safe = true;
            }
            _ => {
                if seen_pad {
                    return false;
                }
            }
        }
    }
    pads <= 2 && !(standard && url_safe)
}

/// Декод кандидата: сначала standard-алфавит, затем url-safe.
///
/// Порядок не косметика: standard — подавляющее большинство входов, и вторая
/// попытка стоит только на токенах с `-_`. Смешанный алфавит отвергают оба
/// движка (`InvalidByte`), что и есть правило «один токен — один алфавит».
///
/// Буфер обёрнут в [`Zeroizing`]: в декодированных байтах лежат оригиналы `ПДн`,
/// а AGENTS §Инженерные инварианты требует zeroize на всех таких буферах.
fn b64_decode(token: &[u8]) -> Option<Zeroizing<Vec<u8>>> {
    use base64::engine::general_purpose::{STANDARD, URL_SAFE};
    STANDARD
        .decode(token)
        .or_else(|_| URL_SAFE.decode(token))
        .map(Zeroizing::new)
        .ok()
}

/// Числительные словами → цифры → валидаторы схемы; спан на фразу словами.
///
/// Цифры, собранные [`numwords::spelled_numbers`], гоняются по тому же оконному
/// конвейеру, что и цифры текста ([`validated_windows`]), а координаты
/// возвращаются на исходную фразу ([`push_hits`] — тот же fail-closed на
/// не-char-границе, что у текстового и base64-путей). Числа короче
/// [`MIN_SPELLED_DIGITS`] в цикл валидаторов не едут вовсе (он же guard года).
///
/// Слой читает **нормализованный** текст и только его: числительные внутри
/// base64-нагрузки не ищем — вложенность обходов ровно один уровень, паритет с
/// `base64_nesting_is_exactly_one_level`.
fn scan_words(
    text: &str,
    norm: &str,
    map: &normalize::OffsetMap,
    wanted: &[(&'static str, ClassId)],
    hits: &mut Vec<Hit>,
) {
    if wanted.is_empty() {
        return;
    }
    for sp in numwords::spelled_numbers(norm) {
        if sp.digits.len() < MIN_SPELLED_DIGITS {
            continue;
        }
        for w in validated_windows(&sp.digits[..], wanted) {
            push_hits(hits, text, map, sp.range.clone(), w.spec, wanted);
        }
    }
}

/// Base64-обход: прогон каскада-0 по декодированной нагрузке каждого кандидата.
///
/// Координаты окон в нагрузке никуда не идут: все хиты этого токена
/// кредитуются на спан исходного токена ([`scan_base64`] заголовок модуля).
///
/// Вложенность — ровно один уровень: нагрузку ведём [`validated_windows`], но
/// [`b64_tokens`] внутри неё не зовём, поэтому `base64(base64(x))` даёт ноль
/// находок (тест `base64_nesting_is_exactly_one_level`).
fn scan_base64(
    text: &str,
    norm: &[u8],
    map: &normalize::OffsetMap,
    wanted: &[(&'static str, ClassId)],
    hits: &mut Vec<Hit>,
) {
    if wanted.is_empty() {
        return;
    }
    for (start, end) in b64_tokens(norm) {
        // Спан кредитывается на токен: если граница токена не char-граница
        // оригинала, fail-closed — находку выбрасываем, а не сдвигаем координаты
        // (маскирование не того байта дороже пропуска).
        let Some(span) = map.map_span_to_original(text, start..end) else {
            continue;
        };
        let Some(payload) = b64_decode(&norm[start..end]) else {
            continue;
        };
        if payload.len() < B64_MIN_PAYLOAD_BYTES {
            continue;
        }
        // Нагрузка — произвольные байты: читаем как UTF-8 с потерями (ASCII-
        // цифры от замены байтов не меняются, а бинарные хвосты становятся
        // U+FFFD и разрезают окна). Дальше — тот же слой, что для текста,
        // поэтому перемычки («044 525 …») внутри декодированного ловит тот же
        // нормализатор и те же окна групп.
        //
        // Честность по [`Zeroizing`]: из трёх буферов залочены два — декод
        // `payload` и его строковая копия `payload_str`. Третий, `dnorm`,
        // приходит из `normalize::normalize` как `Cow<str>`; в ветке
        // `Cow::Owned` (в нагрузке что-то заменялось) это незакрытый
        // `String`-оригинал. Тот же дефект живёт на текстовом пути: там
        // `normalize` вызывается из `scan` и обёрнут ровно так же, поэтому
        // оставляем как есть — паритет путей важнее одностороннего улучшения,
        // а чинить надо в нормализаторе одним движением для обоих (ревью #94
        // F-3, задокументировано, а не проигнорировано).
        let payload_str = Zeroizing::new(String::from_utf8_lossy(payload.as_slice()).into_owned());
        let (dnorm, _) = normalize::normalize(&payload_str);
        // Чексумме нечего проверять без цифр: все валидаторы схемы
        // (ИНН/СНИЛС/ОГРН/Луна/БИК/счёт/IBAN) требуют цифры в окне. Фильтр
        // стоит ПОСЛЕ нормализации, а не на сырых байтах: полноширинные цифры
        // `U+FF10…U+FF19` в байтах декода ASCII-цифрами не являются, а
        // нормализатор сводит их к ASCII (ревью #94 F-1; пара «тот же вход
        // текстом / тот же вход токеном» —
        // `base64_fullwidth_digits_match_the_text_path`). Цена — нормализация
        // каждого кандидата, она меряется в микромере.
        if !dnorm.as_bytes().iter().any(u8::is_ascii_digit) {
            continue;
        }
        for w in validated_windows(dnorm.as_bytes(), wanted) {
            push_span_hits(hits, span, w.spec, DetectionSource::Base64Decode, wanted);
        }
    }
}

