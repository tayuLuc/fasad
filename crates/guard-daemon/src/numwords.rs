//! Слой числительных словами (issue #51 п.2): RU-количественные → цифры.
//!
//! Зачем: каскад 0 видел только цифровые окна, а человек, диктующий номер,
//! число пишет словами — «триста двадцать один миллион двести тысяч сто
//! одиннадцать» (321200111) не детектировался вообще. Цифры, собранные из
//! слов, попадают в тот же оконный конвейер, что и цифры текста: валидатор
//! работает по собранному числу, а координаты спана остаются на оригинале —
//! тот же контур кредитации, что у base64-атома (review #94): нашли кандидатов
//! → подтвердил валидатор → спан = исходный фрагмент (здесь — слова).
//!
//! # Покрыто
//!
//! Количественные имена чисел в **именительном** и **родительном** падеже,
//! полные формы 0..=999 триллионов, женский род единиц («одна тысяча», «две
//! тысячи»):
//!
//! 1. единицы 0..=19;
//! 2. десятки 20..=90;
//! 3. сотни 100..=900;
//! 4. классы масштаба: тысяча (10³), миллион (10⁶), миллиард (10⁹),
//!    триллион (10¹²) — с падежными формами («миллиона», «миллионов»,
//!    «тысячи», «тысяч»);
//! 5. вложенный масштаб 15…18-значных («четыре тысячи пятьсот семьдесят пять
//!    триллионов» = 4·10¹⁵ + …) — иначе 16-значные карты словами недостижимы;
//! 6. любые разделители между словами: токен = цепочка кириллицы, поэтому
//!    дефис, табуляция и перевод строки разделяют слова, а не ломают фразу
//!    («двести-тридцать-восемь» = 238, `case_and_separators`).
//!
//! # Не покрыто (зафиксировано в пул-реквесте, расширение — отдельным шагом)
//!
//! 1. Порядковые: «первый», «семьдесят первый», «тысяча девятьсот семьдесят
//!    первый год» — каталога порядковых нет, фраза обрывается на первом
//!    порядковом слове.
//! 2. Отрицательные: «минус пятьсот» соберётся в 500 без знака; знак
//!    ПДн-номеру не нужен, поэтому в трактат его не брали.
//! 3. Дроби и собирательные: «полтора», «полтора миллиарда», «двое», «трое».
//! 4. Даты словами: «первое мая две тысячи двадцать четвёртого».
//! 5. Грамматика «цифра за цифрой» («один два три»): посимвольная диктовка
//!    номера — отдельная задача, а склейка её в число дала бы ложные FP,
//!    поэтому разбор на каждом несогласованном слове рестартует и числа **не
//!    склеиваются** (`digits_never_concatenate_across_a_break`).
//! 6. Ведущие нули словами не выражаются, значит БИК (9 цифр с ведущего `04`)
//!    и 20-значный счёт (с ведущего `30…50`, требует 10¹⁹ ≥ квинтиллиона)
//!    этим слоем недостижимы — следствие формата записи, а не дыра разбора.
//! 7. Падежи кроме именительного/родительного (дательный, творительный,
//!    предложный) и союз «и» между разрядами: «сто и пять» = 100 | 5, а не 105
//!    (союз не лексема, он разрывает фразу).
//!
//! # Guard года — структурный, не список слов
//!
//! Минимальная длина окна в `cascade0::DIGIT_SPECS` = 9 цифр
//! (`bik_format`), и `cascade0::MIN_SPELLED_DIGITS` равна ей: собранное число
//! короче девяти цифр до цикла валидаторов не доезжает вовсе. Поэтому
//! четырёхзначному году словами некому подтверждаться: «тысяча девятьсот
//! семьдесят один» = 1971 спана не даёт ни при каком совпадении. Связь
//! константы с таблицей длин сверяет `spelled_floor_is_the_shortest_digit_spec`.
//!
//! Лексика каноническая; `ё` принимается в обеих ипостасях («трехсот»
//! и «трёхсот»), регистр не важен, разделители между словами любые (пробел,
//! дефис, перевод строки).

use std::ops::Range;

use zeroize::Zeroizing;

/// Тысяча (10³).
const THOUSAND: u128 = 1_000;
/// Миллион (10⁶).
const MILLION: u128 = 1_000_000;
/// Миллиард (10⁹).
const MILLIARD: u128 = 1_000_000_000;
/// Триллион (10¹²).
const TRILLION: u128 = 1_000_000_000_000;

/// Признак заполненности разряда незакрытого класса (флаги, не `bool`-поля:
/// разрядов три, и они всегда живут одним битовым набором).
const HAS_UNIT: u8 = 1;
/// Десятки приняты.
const HAS_TEN: u8 = 2;
/// Сотни приняты.
const HAS_HUNDRED: u8 = 4;

/// Роль слова в имени числа.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Word {
    /// Единицы 0..=19 (родовые формы «одна», «две» — то же значение).
    Unit(u128),
    /// Десятки 20..=90.
    Ten(u128),
    /// Сотни 100..=900.
    Hundred(u128),
    /// Класс масштаба (значение = сама степень десятки).
    Scale(u128),
}

/// Роль «единица».
const fn unit(v: u128) -> Word {
    Word::Unit(v)
}

/// Роль «десятки».
const fn ten(v: u128) -> Word {
    Word::Ten(v)
}

/// Роль «сотни».
const fn hundred(v: u128) -> Word {
    Word::Hundred(v)
}

/// Роль «класс масштаба».
const fn scale(v: u128) -> Word {
    Word::Scale(v)
}

/// Степень класса масштаба (1000 → 3): порядок классов обязан убывать,
/// «миллион тысяча» — имя числа, «тысяча миллион» — нет.
const fn scale_pow(v: u128) -> u32 {
    match v {
        THOUSAND => 3,
        MILLION => 6,
        MILLIARD => 9,
        TRILLION => 12,
        _ => 0,
    }
}

/// Слово → роль; `None` — слово не числительное, на нём фраза заканчивается.
///
/// Каталог собран из канонических парадигм: именительный падеж (единицы —
/// всех трёх родов) + родительный (самый частый в деловой прозе: «нет
/// тридцати одного миллиона»), формы масштаба — с падежными окончаниями.
fn word(w: &str) -> Option<Word> {
    match w {
        // Единицы: именительный (три рода) + родительный/винительный.
        "ноль" | "нуля" | "нулей" | "нулем" => Some(unit(0)),
        "один" | "одна" | "одно" | "одного" | "одной" | "одному" | "одним" | "одну" => {
            Some(unit(1))
        }
        "два" | "две" | "двух" | "двум" | "двумя" => Some(unit(2)),
        "три" | "трёх" | "трех" | "трём" | "трем" | "тремя" => {
            Some(unit(3))
        }
        "четыре" | "четырёх" | "четырех" | "четырём" | "четырем" | "четырьмя" => {
            Some(unit(4))
        }
        "пять" | "пяти" | "пятью" => Some(unit(5)),
        "шесть" | "шести" | "шестью" => Some(unit(6)),
        "семь" | "семи" | "семью" => Some(unit(7)),
        "восемь" | "восьми" | "восемью" => Some(unit(8)),
        "девять" | "девяти" | "девятью" => Some(unit(9)),
        "десять" | "десяти" | "десятью" => Some(unit(10)),
        "одиннадцать" | "одиннадцати" => Some(unit(11)),
        "двенадцать" | "двенадцати" => Some(unit(12)),
        "тринадцать" | "тринадцати" => Some(unit(13)),
        "четырнадцать" | "четырнадцати" => Some(unit(14)),
        "пятнадцать" | "пятнадцати" => Some(unit(15)),
        "шестнадцать" | "шестнадцати" => Some(unit(16)),
        "семнадцать" | "семнадцати" => Some(unit(17)),
        "восемнадцать" | "восемнадцати" => Some(unit(18)),
        "девятнадцать" | "девятнадцати" => Some(unit(19)),
        // Десятки.
        "двадцать" | "двадцати" => Some(ten(20)),
        "тридцать" | "тридцати" => Some(ten(30)),
        "сорок" | "сорока" => Some(ten(40)),
        "пятьдесят" | "пятидесяти" | "пятидесятью" => Some(ten(50)),
        "шестьдесят" | "шестидесяти" | "шестидесятью" => {
            Some(ten(60))
        }
        "семьдесят" | "семидесяти" | "семидесятью" => Some(ten(70)),
        "восемьдесят" | "восьмидесяти" | "восьмидесятью" => {
            Some(ten(80))
        }
        "девяносто" | "девяноста" => Some(ten(90)),
        // Сотни.
        "сто" | "ста" | "стами" => Some(hundred(100)),
        "двести" | "двухсот" | "двумястами" => Some(hundred(200)),
        "триста" | "трёхсот" | "трехсот" | "тремястами" => {
            Some(hundred(300))
        }
        "четыреста" | "четырёхсот" | "четырехсот" | "четырьмястами" => {
            Some(hundred(400))
        }
        "пятьсот" | "пятисот" | "пятьюстами" => Some(hundred(500)),
        "шестьсот" | "шестисот" | "шестьюстами" => Some(hundred(600)),
        "семьсот" | "семисот" | "семьюстами" => Some(hundred(700)),
        "восемьсот" | "восьмисот" | "восемьюстами" => {
            Some(hundred(800))
        }
        "девятьсот" | "девятисот" | "девятьюстами" => {
            Some(hundred(900))
        }
        // Классы масштаба: именительный + родительный + частые падежные.
        "тысяча" | "тысячи" | "тысяч" | "тысячу" | "тысяче" | "тысячей" | "тысячам"
        | "тысячами" => Some(scale(THOUSAND)),
        "миллион"
        | "миллиона"
        | "миллионов"
        | "миллиону"
        | "миллионом"
        | "миллионе"
        | "миллионам"
        | "миллионами" => Some(scale(MILLION)),
        "миллиард"
        | "миллиарда"
        | "миллиардов"
        | "миллиарду"
        | "миллиардом"
        | "миллиарде"
        | "миллиардам"
        | "миллиардами" => Some(scale(MILLIARD)),
        "триллион"
        | "триллиона"
        | "триллионов"
        | "триллиону"
        | "триллионом"
        | "триллионе"
        | "триллионам"
        | "триллионами" => Some(scale(TRILLION)),
        _ => None,
    }
}

/// Имя числа, собранное из слов: цифры + байтовый диапазон фразы.
#[derive(Debug, Clone)]
pub struct Spelled {
    /// Диапазон словесной фразы в **нормализованном** тексте — по нему
    /// [`guard_detectors::normalize::OffsetMap`] возвращает координаты оригинала (тот же
    /// контур, что у base64-атома).
    pub range: Range<usize>,
    /// Цифры числа в ASCII. Секрет-класс: буфер затирается на дропе.
    pub digits: Zeroizing<Vec<u8>>,
}

/// Все имена чисел в тексте: по одному на фразу, в порядке появления.
///
/// Разбор — жадный maximal munch с рестартом: фраза продолжается, пока слово
/// согласуется с грамматикой имени числа; на первом несогласном слове
/// накопленное значение фиксируется, а разбор продолжается **с этого слова**.
/// Поэтому «один два три» даёт три одноцифровых числа, а не «123»:
/// посимвольная диктовка не склеивается, ложных FP из неё не рождается.
#[must_use]
pub fn spelled_numbers(text: &str) -> Vec<Spelled> {
    if !has_cyrillic(text.as_bytes()) {
        return Vec::new();
    }
    let mut out: Vec<Spelled> = Vec::new();
    let mut acc = Acc::default();
    let mut iter = Words::new(text);
    while let Some((start, end, token)) = iter.next_word() {
        match word(token) {
            Some(found) => acc.push(found, start, end, &mut out),
            None => acc.finish(&mut out),
        }
    }
    acc.finish(&mut out);
    out
}

/// Есть ли в тексте кириллица (ведущие байты `0xD0`/`0xD1` = U+0400..U+04FF).
/// Дешёвый префильтр горячего пути: в латинском тексте словесных чисел не
/// бывает, и такой текст стоит каскаду один проход по байтам.
fn has_cyrillic(bytes: &[u8]) -> bool {
    bytes.iter().any(|b| *b == 0xD0 || *b == 0xD1)
}

/// Итог попытки вставить слово в фразу.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Accept {
    /// Слово в фразу встало.
    Ok,
    /// Слово фразе противоречит: фразу закрыть, разбор продолжить с него.
    Break,
}

/// Аккумулятор фразы: `total` (закрытые классы масштаба) + `current`
/// (незакрытый класс), порядок разрядов «сотни → десятки → единицы», классы
/// масштаба строго убывают (или вложены: «тысячи триллионов»).
#[derive(Debug, Default, Clone, Copy)]
struct Acc {
    /// Сумма закрытых классов (после слов масштаба).
    total: u128,
    /// Незакрытый класс: сотни/десятки/единицы, ждущие свой масштаб.
    current: u128,
    /// Степень последнего принятого класса масштаба (0 = классов не было).
    last_pow: u32,
    /// Заполненность разрядов незакрытого класса (`HAS_*`).
    flags: u8,
    /// Байтовый начало фразы.
    start: usize,
    /// Байтовый конец последнего принятого слова.
    end: usize,
    /// Принято ли хотя бы одно слово.
    nonempty: bool,
}

impl Acc {
    /// Принять слово; на конфликт — закрыть фразу и открыть новую с этого же
    /// слова (пустой аккумулятор слово принимает всегда, см. `accept`).
    fn push(&mut self, w: Word, start: usize, end: usize, out: &mut Vec<Spelled>) {
        if self.accept(w, start, end) == Accept::Break {
            self.finish(out);
            debug_assert_eq!(self.accept(w, start, end), Accept::Ok);
        }
    }

    /// Вставить слово в аккумулятор, ничего не выдавая.
    fn accept(&mut self, w: Word, start: usize, end: usize) -> Accept {
        let next = match w {
            Word::Unit(v) => {
                if self.has(HAS_UNIT) {
                    return Accept::Break;
                }
                (
                    self.total,
                    self.current.saturating_add(v),
                    self.last_pow,
                    self.flags | HAS_UNIT,
                )
            }
            Word::Ten(v) => {
                if self.has(HAS_UNIT | HAS_TEN) {
                    return Accept::Break;
                }
                (
                    self.total,
                    self.current.saturating_add(v),
                    self.last_pow,
                    self.flags | HAS_TEN,
                )
            }
            Word::Hundred(v) => {
                if self.flags != 0 {
                    return Accept::Break;
                }
                (
                    self.total,
                    self.current.saturating_add(v),
                    self.last_pow,
                    HAS_HUNDRED,
                )
            }
            Word::Scale(v) => {
                let pow = scale_pow(v);
                match self.closing(v, pow) {
                    Some(total) => (total, 0, pow, 0),
                    None => return Accept::Break,
                }
            }
        };
        self.total = next.0;
        self.current = next.1;
        self.last_pow = next.2;
        self.flags = next.3;
        if !self.nonempty {
            self.start = start;
            self.nonempty = true;
        }
        self.end = end;
        Accept::Ok
    }

    /// Новое `total` после слова масштаба: `None` — класс нарушает порядок.
    ///
    /// Арифметика на `saturating_*` с проверкой: имена чисел до 999 триллионов
    /// в `u128` влезают с запасом (потолок вложенного «тысячи триллионов» —
    /// 10¹⁸), так что насыщение здесь — страховка от абсурдного входа, а не
    /// рабочий путь.
    fn closing(&self, v: u128, pow: u32) -> Option<u128> {
        let mult = if self.current == 0 { 1 } else { self.current };
        let total = if self.last_pow == 0 || pow > self.last_pow {
            // Вложение («четыре тысячи … триллионов») и первый класс:
            // (сумма + текущий класс) × масштаб.
            self.total.checked_add(mult)?.checked_mul(v)?
        } else if pow < self.last_pow {
            // Обычный спуск («миллиардов … миллионов … тысяч»).
            self.total.checked_add(mult.checked_mul(v)?)?
        } else {
            return None;
        };
        Some(total)
    }

    /// Закрыть фразу: выдать число и сброситься. Ноль не выдаётся — одна
    /// цифра «0» не подтверждается ни одним валидатором схемы.
    fn finish(&mut self, out: &mut Vec<Spelled>) {
        if !self.nonempty {
            return;
        }
        let value = self.total.saturating_add(self.current);
        let range = self.start..self.end;
        *self = Acc::default();
        if value > 0 {
            out.push(Spelled {
                range,
                digits: Zeroizing::new(value.to_string().into_bytes()),
            });
        }
    }

    /// Заполнен ли один из разрядов (`mask` — биты `HAS_*`).
    fn has(&self, mask: u8) -> bool {
        self.flags & mask != 0
    }
}

/// Скан кириллических слов: слова текста в нижнем регистре.
///
/// Слово = максимальная цепочка кириллических литер (U+0400..U+04FF); всё
/// остальное (пробелы, дефисы, цифры, латиница) — разделитель. Токенизация
/// идёт по слову целиком, а не по префиксу: «столица» — одно слово, не «сто» +
/// «лица», поэтому префиксных ложных срабатываний лексикон не производит.
struct Words<'a> {
    bytes: &'a [u8],
    pos: usize,
    key: String,
}

impl<'a> Words<'a> {
    /// Новый скан по тексту.
    fn new(text: &'a str) -> Self {
        Self {
            bytes: text.as_bytes(),
            pos: 0,
            key: String::new(),
        }
    }

    /// Следующее слово: (байтовое начало, байтовый конец, ключ в нижнем
    /// регистре). Буфер ключа переиспользуется: на слово аллокации нет.
    fn next_word(&mut self) -> Option<(usize, usize, &str)> {
        loop {
            self.skip_separators();
            if self.pos >= self.bytes.len() {
                return None;
            }
            self.key.clear();
            let start = self.pos;
            while let Some(chunk) = self.cyrillic_char() {
                self.key.extend(chunk.chars().flat_map(char::to_lowercase));
            }
            if self.key.is_empty() {
                // Оборвалась UTF-8 последовательность на ведущем байте
                // (нормализованный текст такого не даёт; шаг вперёд — чтобы
                // скан не зациклился на битом входе).
                self.pos += 1;
                continue;
            }
            return Some((start, self.pos, &self.key));
        }
    }

    /// Пропустить разделители (всё, что не кириллица).
    fn skip_separators(&mut self) {
        while self.pos < self.bytes.len() && !is_cyrillic_lead(self.bytes[self.pos]) {
            self.pos += 1;
        }
    }

    /// Съесть один кириллический символ (2 байта) и вернуть его строкой.
    fn cyrillic_char(&mut self) -> Option<&'a str> {
        if self.pos + 1 >= self.bytes.len() || !is_cyrillic_lead(self.bytes[self.pos]) {
            return None;
        }
        let end = self.pos + 2;
        let chunk = std::str::from_utf8(&self.bytes[self.pos..end]).ok()?;
        self.pos = end;
        Some(chunk)
    }
}

/// Ведущий байт кириллического символа (U+0400..U+04FF).
const fn is_cyrillic_lead(b: u8) -> bool {
    b == 0xD0 || b == 0xD1
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)] // в тестах паника = канал ответа
mod tests {
    use super::{scale_pow, spelled_numbers};

    /// Разбор → собранные числа (строки цифр). Ожидаемое значение считается
    /// арифметикой разрядов в комментарии, НЕ этим кодом (AGENTS §Дисциплина
    /// фактов п.3: запрещено вычислять ожидаемое проверяемой функцией).
    fn digits(text: &str) -> Vec<String> {
        spelled_numbers(text)
            .into_iter()
            .map(|s| String::from_utf8(s.digits.to_vec()).unwrap_or_default())
            .collect()
    }

    /// Разбор → (число, исходная фраза): спан обязан покрывать слова.
    fn spans(text: &str) -> Vec<(String, String)> {
        spelled_numbers(text)
            .into_iter()
            .map(|s| {
                (
                    String::from_utf8(s.digits.to_vec()).unwrap_or_default(),
                    text[s.range].to_string(),
                )
            })
            .collect()
    }

    /// Векторы задачи (issue #51 п.2).
    #[test]
    fn task_vectors() {
        // 321·10⁶ + 200·10³ + 111.
        assert_eq!(
            digits("триста двадцать один миллион двести тысяч сто одиннадцать"),
            ["321200111"]
        );
        // 11·10⁶ + 200·10³ + 111.
        assert_eq!(
            digits("одиннадцать миллионов двести тысяч сто одиннадцать"),
            ["11200111"]
        );
        assert_eq!(digits("двести тридцать восемь"), ["238"]);
        // 1·10³ + 223: женский род «одна тысяча».
        assert_eq!(digits("одна тысяча двести двадцать три"), ["1223"]);
    }

    /// Женский род единиц согласуется с «тысяча».
    #[test]
    fn feminine_agreement_with_thousand() {
        // (200 + 20 + 1)·10³.
        assert_eq!(digits("двести двадцать одна тысяча"), ["221000"]);
        assert_eq!(digits("две тысячи"), ["2000"]);
        assert_eq!(digits("пять тысяч"), ["5000"]);
        assert_eq!(digits("триста двадцать одна тысяча"), ["321000"]);
    }

    /// Родительный падеж входит дёшево: те же значения, лексика шире.
    #[test]
    fn genitive_is_covered() {
        // 31·10⁶.
        assert_eq!(digits("тридцати одного миллиона"), ["31000000"]);
        // (31·10⁶) + 200·10³ + 111.
        assert_eq!(
            digits("тридцати одного миллиона двести тысяч сто одиннадцать"),
            ["31200111"]
        );
        assert_eq!(digits("пяти триллионов"), ["5000000000000"]);
    }

    /// Класс масштаба без количества = одна единица класса («миллион рублей»).
    #[test]
    fn scale_word_without_count_is_one_unit() {
        assert_eq!(digits("миллион"), ["1000000"]);
        assert_eq!(digits("тысяча"), ["1000"]);
        assert_eq!(digits("тысяча девятьсот семьдесят один"), ["1971"]);
    }

    /// Вложенный масштаб: «тысячи триллионов» = 10¹⁵, иначе 16-значные карты
    /// словами были бы недостижимы.
    #[test]
    fn nested_scale_reaches_card_pan_length() {
        // (4·10³ + 575)·10¹² + 503·10⁹ + 590·10⁶ + 352·10³ + 993.
        assert_eq!(
            digits(
                "четыре тысячи пятьсот семьдесят пять триллионов пятьсот три миллиарда \
                 пятьсот девяносто миллионов триста пятьдесят две тысячи девятьсот \
                 девяносто три"
            ),
            ["4575503590352993"]
        );
    }

    /// Регистр и разделители не значимы.
    #[test]
    fn case_and_separators() {
        assert_eq!(digits("Двести тридцать восемь"), ["238"]);
        assert_eq!(digits("двести-тридцать-восемь"), ["238"]);
        assert_eq!(digits("  сто\tпятьдесят  "), ["150"]);
        assert_eq!(digits("ТРИСТА ДВАДЦАТЬ ОДИН"), ["321"]);
        // Перенос строки — разделитель той же природы, что пробел: фаза
        // нормализатора его не съедает, слой его не боится.
        assert_eq!(digits("двести\nтридцать"), ["230"]);
    }

    /// «ё» в обоих написаниях.
    #[test]
    fn yo_is_accepted_both_ways() {
        assert_eq!(digits("трёхсот тридцати трёх тысяч"), ["333000"]);
        assert_eq!(digits("трехсот тридцати трех тысяч"), ["333000"]);
    }

    /// Посимвольная диктовка не склеивается: «один два три» = 1, 2, 3.
    #[test]
    fn digits_never_concatenate_across_a_break() {
        assert_eq!(digits("один два три"), ["1", "2", "3"]);
        assert_eq!(digits("сто рублей и двести"), ["100", "200"]);
        // Союз «и» между разрядами — не лексема: «сто и пять» = 100 | 5.
        assert_eq!(digits("сто и пять"), ["100", "5"]);
    }

    /// Нарушение грамматики закрывает фразу, а не превращается в мусор.
    #[test]
    fn grammar_violation_restarts_instead_of_garbage() {
        // Два десятка в одном классе не бывает: 20 | 30, а не 50.
        assert_eq!(digits("двадцать тридцать"), ["20", "30"]);
        // Единица раньше десятки — новый класс.
        assert_eq!(digits("один двадцать"), ["1", "20"]);
        // Классы масштаба убывают → складываются: 1·10⁶ + 1·10³.
        assert_eq!(digits("миллион тысяча"), ["1001000"]);
        // Повтор класса: «пять миллионов два миллиона» — не имя числа.
        // Незакрытый класс («два») уезжает в закрываемое значение, а слово
        // масштаба начинает новую фразу со своей единичной стоимости:
        // 5·10⁶ + 2 | 1·10⁶.
        assert_eq!(
            digits("пять миллионов два миллиона"),
            ["5000002", "1000000"]
        );
        // Две сотни подряд: 200 | 300.
        assert_eq!(digits("двести триста"), ["200", "300"]);
    }

    /// Слово целиком, а не префикс: «столица» не даёт «сто».
    #[test]
    fn prefixes_of_longer_words_are_not_numbers() {
        assert_eq!(digits("столица"), Vec::<String>::new());
        assert_eq!(digits("тринадцатиэтажный дом"), Vec::<String>::new());
        assert_eq!(digits("единица тысячный"), Vec::<String>::new());
        // «тысяч» само по себе — класс масштаба, он и вне «столицы» число:
        // связное слово лексиконом не режется (проверка на префиксе выше).
        assert_eq!(digits("столица тысяч"), ["1000"]);
    }

    /// Спан = исходная фраза словами, целиком.
    #[test]
    fn span_is_the_whole_word_phrase() {
        let text = "ИНН клиента: восемьсот двадцать пять миллиардов девятьсот шестьдесят четыре";
        let got = spans(text);
        assert_eq!(got.len(), 1, "одна фраза числительного: {got:?}");
        assert_eq!(
            got[0].1,
            "восемьсот двадцать пять миллиардов девятьсот шестьдесят четыре"
        );
    }

    /// Порядковое обрывает фразу: год остаётся 1970 (и не доезжает до
    /// валидаторов — см. `year_in_words_is_not_a_hit` в каскаде).
    #[test]
    fn ordinal_breaks_the_phrase() {
        assert_eq!(digits("тысяча девятьсот семьдесят первый год"), ["1970"]);
    }

    /// Знак и дробь не покрываются: «минус» и «полтора» не из лексикона, они
    /// просто не входят во фразу — дробное количество собирается как целое
    /// («полтора миллиона» → 10⁶, слово «полтора» потеряно). Это
    /// задокументированная цена слоя: хит даёт только подтверждённая чексумма.
    #[test]
    fn sign_and_fraction_are_not_covered() {
        // (1·10³ + 500): «минус» просто не входит в фразу.
        assert_eq!(digits("минус тысяча пятьсот"), ["1500"]);
        assert_eq!(digits("минус пятьсот"), ["500"]);
        assert_eq!(digits("полтора миллиона"), ["1000000"]);
        assert_eq!(digits("полтора"), Vec::<String>::new());
    }

    /// Латиница без кириллицы стоит один проход по байтам и пустой результат.
    #[test]
    fn latin_only_text_is_skipped() {
        assert!(spelled_numbers("Invoice 12345 due 2024-01-01").is_empty());
        assert!(spelled_numbers("five six seven").is_empty());
    }

    /// Степени классов масштабированы по возрастанию — порядок убывания,
    /// который требует аккумулятор, определён именно ими.
    #[test]
    fn scale_powers_are_ordered() {
        assert_eq!(
            (
                scale_pow(1_000),
                scale_pow(1_000_000),
                scale_pow(1_000_000_000),
                scale_pow(1_000_000_000_000)
            ),
            (3, 6, 9, 12)
        );
        assert_eq!(scale_pow(10), 0, "неизвестный класс масштаба");
    }
}
